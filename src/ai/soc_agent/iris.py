def _ip_ioc_valid(ip: str) -> bool:
    """IP usable as an IOC: neither 'none', nor loopback, nor unspecified, nor
    the SOC infrastructure.

    Discards the noise that polluted the threat intel (`ip-any = none`, 0.0.0.0,
    127.0.0.1, link-local, multicast).

    The SOC itself (`config.SOC_INFRA_IPS`: manager, indexer, IRIS, Shuffle) is
    excluded here rather than in every caller: this is the only crossing point
    common to the IOCs and to the choice of blocking targets in `mitigate`, hence
    the only place where the exclusion cannot be forgotten by a future block. The
    SIEM talks to the whole estate; its IP as `srcip` or as a connection target
    says nothing about an attack, and blocking it cuts the SOC off from its
    agents."""
    try:
        o = ipaddress.ip_address(str(ip).strip())
    except ValueError:
        return False
    if str(o) in config.SOC_INFRA_IPS:
        return False
    return not (o.is_loopback or o.is_unspecified or o.is_link_local
                or o.is_multicast)


def _ip_internal(ip: str) -> bool:
    """True if the IP belongs to a subnet of the estate (cf.
    config.NETWORKS_INTERNAL).

    Deliberately NOT `is_private`: a C2 can live in RFC1918 (VPN, private
    cloud...) — only membership of the declared subnets of the estate counts as
    "internal"."""
    try:
        o = ipaddress.ip_address(str(ip).strip())
    except ValueError:
        return False
    return any(o in n for n in _NETS_INTERNAL)


# Recurring accent typos of the model (French written without accents), fixed
# deterministically on the LLM narrative. Limited to the forms with NO collision
# with English/MITRE: "privilege" (Privilege Escalation) and "elevation" are
# therefore EXCLUDED. "reseau" has no English homograph.
_ACCENTS = {
    "acces": "accès", "detecte": "détecté", "detectee": "détectée",
    "detectes": "détectés", "detectees": "détectées", "deja": "déjà",
    "reseau": "réseau", "reseaux": "réseaux",
}
_RE_ACCENTS = re.compile(r"\b(" + "|".join(_ACCENTS) + r")\b", re.IGNORECASE)


def _fix_accents(txt: str) -> str:
    """Replace the accent typos of the LLM narrative, preserving the case."""
    def repl(m):
        word = m.group(0)
        corr = _ACCENTS[word.lower()]
        return corr.capitalize() if word[0].isupper() else corr
    return _RE_ACCENTS.sub(repl, txt or "")


def _decode_proctitle(full_log: str) -> str:
    """Command line decoded from the hex proctitle of an auditd log."""
    m = _RE_PROCTITLE.search(full_log or "")
    if not m:
        return ""
    try:
        return bytes.fromhex(m.group(1)).replace(b"\x00", b" ").decode(
            "utf-8", "replace")
    except ValueError:
        return ""


def _ips_revshell(alert: dict) -> set[str]:
    """Target IPs of a /dev/tcp|/dev/udp redirection in the alert's command.

    Looks in the plain full_log, in the decoded hex proctitle and in the
    description. Does NOT filter internal/external: the caller decides (context
    IOC vs blocking target). This is the only source of the C2 IP for an auditd
    reverse shell — the execve event carries no `srcip`, so without it the
    detected C2 (rule 100650) was never blocked (measured regression)."""
    raw = alert["raw"] if isinstance(alert.get("raw"), dict) else json.loads(
        alert.get("raw") or "{}")
    full_log = raw.get("full_log") or ""
    ips: set[str] = set()
    for text in (full_log, _decode_proctitle(full_log),
                  alert.get("rule_desc") or ""):
        for ip, _port in _RE_REVSHELL.findall(text):
            if _ip_ioc_valid(ip):
                ips.add(ip)
    return ips


def _path_target(p: str | None) -> str | None:
    """Real path on the scanned machine, without the sshfs mount prefix.

    The YARITRUST scanner mounts every host under /mnt/yaritrust/<host>_<ip>/ and
    scans through it. `data.file_path` already carries the cleaned path, but the
    alerts predating the fix only have `yara.scan_path`, prefixed. Without this
    removal, the SAME file produces two distinct IOCs in the case (one prefixed,
    one not), and neither is usable as is on the host concerned.
    """
    if not p:
        return None
    return _RE_MOUNT_SCAN.sub("/", p, count=1)


def _path_suspicious(p: str | None) -> bool:
    if not p:
        return False
    if any(p.startswith(d) for d in _DIRS_SUSPICIOUS):
        return True
    base = p.rsplit("/", 1)[-1]
    # Hidden executable (dot-prefixed name) outside the legitimate locations.
    return base.startswith(".") and not p.startswith(("/etc", "/home", "/root/."))


def _paths_argv(audit: dict, full_log: str) -> list[str]:
    """Suspicious file paths quoted as an ARGUMENT of an auditd command.

    `audit.file.name` and `entity` carry the binary the KERNEL loaded, not the
    file it acts on: for `python3 /tmp/x.py` that is /usr/bin/python3, for
    `insmod /tmp/rk.ko` that is /usr/bin/kmod (and `audit.file.name` may even
    point at an unrelated file, /etc/hosts being read by the loader). The
    artefact dropped by the attacker — the only one huntable across the rest of
    the estate — therefore only lives in the argv.

    Two sources, in this order: the `audit.execve` field decoded by Wazuh
    (a0, a1...) and, failing that, the hex proctitle of the full_log. The paths
    of the session machinery (systemd private mounts, X11 sockets) are discarded:
    they sit in /tmp owing nothing to the attacker.
    """
    chunks: list[str] = []
    execve = audit.get("execve")
    if isinstance(execve, dict):
        def _rank(key: str) -> tuple[int, str]:
            suffix = str(key).lstrip("a")
            return (int(suffix), "") if suffix.isdigit() else (10**6, str(key))
        chunks += [str(v) for _, v in sorted(execve.items(),
                                               key=lambda kv: _rank(kv[0]))]
    chunks.append(_decode_proctitle(full_log))

    out: list[str] = []
    seen: set[str] = set()
    for text in chunks:
        for path in _RE_PATH_ARGV.findall(text or ""):
            path = path.rstrip(".,;:")
            if path in seen or _RE_ARGV_NOISE.search(path):
                continue
            if not _path_suspicious(path):
                continue
            seen.add(path)
            out.append(path)
    return out


# Order of preference for REPRESENTING a file in the IOC list. A hash
# identifies the content: it survives a rename, holds on any machine, and can be
# shared as is with a third party or a reputation engine. A path only holds on
# the host where it was seen. Hence hash > filename.
_PRIORITY_IOC_FILE = ("sha256", "sha1", "md5")


def _ioc_file(path: str | None, hashes: dict, context: str
                 ) -> tuple[str, str, str] | None:
    """ONE single IOC per file, the rest folded into the description.

    The same file used to produce up to three entries (path, sha256, md5). The
    IOC list of a case became unreadable and its counter misleading: six detected
    files appeared there as eighteen distinct indicators, and nothing said those
    three lines designated the same object.

    No information is lost — the other hashes and the path stay written in the
    description, so they remain readable in the case and searchable. What changes
    is the number of LINES: one per real artefact.
    """
    principal = next(((t, hashes[t]) for t in _PRIORITY_IOC_FILE
                      if hashes.get(t)), None)
    extras = []
    if principal:
        type_ioc, value = principal
        if path:
            extras.append(f"fichier {path}")
    elif path:
        type_ioc, value = "filename", path
    else:
        return None

    # The hashes not kept as the main value stay displayed: an analyst who only
    # has an MD5 at hand must be able to make the link.
    extras += [f"{t} {hashes[t]}" for t in _PRIORITY_IOC_FILE
                    if hashes.get(t) and hashes[t] != value]

    description = context
    if extras:
        description = f"{context} · " + " · ".join(extras)
    return str(value), type_ioc, description


# Extensions kept for a dropped Windows "executable".
_EXE_WIN = (".exe", ".dll", ".ps1", ".bat", ".scr", ".com", ".vbs", ".js")


def _mitre_observed(alerts: list[dict]) -> set[str]:
    """ATT&CK ids carried by the rules that fired on the incident."""
    out: set[str] = set()
    for a in alerts:
        for t in (a.get("mitre_ids") or []):
            if t:
                out.add(str(t).strip())
    return out - {""}


# Techniques whose remediation follows from NO active-response action: they
# leave the attacker able to come back even once the host is cleaned. A
# purple-team exercise detected `kerberos::golden` without anything anywhere
# saying the krbtgt secret had to be changed — the incident was closed with a
# forged ticket valid for ten years.
_REMEDIATIONS_OUTSIDE_SCOPE = {
    "T1558.001": (
        "Golden Ticket — le hash du compte **krbtgt** est compromis",
        "Aucune action automatique ne corrige cela. Tant que le secret n'est "
        "pas renouvelé, l'attaquant peut forger un TGT pour n'importe quel "
        "compte du domaine, y compris après nettoyage complet des hôtes. "
        "**Renouveler le mot de passe de krbtgt DEUX fois**, en laissant "
        "s'écouler au moins la durée de vie maximale d'un ticket (10 h par "
        "défaut) entre les deux : le premier renouvellement seul laisse "
        "l'ancienne clé valide."),
    "T1003.006": (
        "DCSync — la base de comptes du domaine a pu être répliquée",
        "Considérer TOUS les secrets du domaine comme divulgués (comptes de "
        "service, krbtgt, comptes machine). Renouveler krbtgt deux fois et les "
        "mots de passe des comptes à privilèges."),
    "T1003.003": (
        "NTDS.dit — la base Active Directory a pu être copiée",
        "Même portée qu'un DCSync : tous les hashs du domaine sont à "
        "considérer comme connus de l'attaquant."),
    "T1550.002": (
        "Pass-the-Hash — un hash NTLM valide est entre les mains de l'attaquant",
        "Renouveler le mot de passe du compte concerné. Désactiver le compte "
        "ne suffit pas si le hash sert ailleurs dans le domaine."),
}


def _section_remediation_outside_scope(triage: dict,
                                     alerts: list[dict]) -> str:
    """What the automation can NOT repair, and has to be done by hand.

    An autonomous remediation isolates, blocks, kills and disables. It does not
    renew a domain secret. When the attack chain contains a theft of AD
    credentials, the incident is not over once the host is cleaned, and the
    report must say so in plain words.
    """
    seen = _mitre_observed(alerts) | {(triage.get("mitre") or "").strip()}
    concerned = [(t, _REMEDIATIONS_OUTSIDE_SCOPE[t])
                  for t in sorted(_REMEDIATIONS_OUTSIDE_SCOPE) if t in seen]
    if not concerned:
        return ""
    lines = [
        "## À faire à la main — hors de portée de la remédiation automatique",
        "",
        "Les actions automatiques (isolation, blocage, arrêt de process, "
        "désactivation de compte) ne corrigent PAS ce qui suit. Tant que ces "
        "points ne sont pas traités, l'attaquant garde un moyen de revenir.",
        "",
    ]
    for tech, (title, quoi) in concerned:
        lines += [f"### {tech} — {title}", "", quoi, ""]
    return "\n".join(lines)


def _norm_win_path(raw) -> str:
    r"""Windows path with single backslashes.

    The eventchannel JSON arrives with DOUBLED backslashes and Wazuh keeps them:
    `C:\\Windows\\System32\\cmd.exe` is stored with two characters between each
    segment. Any prefix test on a system directory fails silently without this
    normalisation — that is what sent 26 quarantine orders on System32 binaries
    on 2026-08-02 (cf. `mitigate._norm_win_path`, same fix).
    """
    p = str(raw or "").strip().strip('"')
    while "\\\\" in p:
        p = p.replace("\\\\", "\\")
    return p


def _exe_windows_suspicious(path: str) -> bool:
    """Windows executable outside a system directory: IOC candidate.

    A signed System32 binary launched by the attacker is a matter for behavioural
    detection, not for indicators: hunting it across the estate would only return
    noise. What can be hunted is what the attacker BROUGHT.
    """
    pl = path.lower()
    return bool(path and ":\\" in path and pl.endswith(_EXE_WIN)
                and not pl.startswith(config.VT_DIRS_SYSTEM)
                and "__psscriptpolicytest_" not in pl)


def _is_registry_key(path: str | None) -> bool:
    """True for a Windows registry key (not a file, so not an IOC)."""
    return str(path or "").upper().startswith(("HKEY_", "HKLM\\", "HKCU\\",
                                                 "HKLM/", "HKCU/"))


def _vt_malicious(vt: dict) -> bool:
    """True if VirusTotal really returned a POSITIVE verdict.

    The integration writes `found` (does VT know this hash) and `malicious`
    (number of positive engines), both as strings. Without this test, a hash
    unknown to VT became an indicator of compromise in the case.
    """
    def _n(v):
        try:
            return int(str(v).strip() or 0)
        except ValueError:
            return 0
    return _n(vt.get("found")) > 0 and _n(vt.get("malicious")) > 0


def _iocs(alerts: list[dict]) -> list[tuple[str, str, str]]:
    """Real attack indicators, deduplicated. Best-effort.

    We only surface what characterises the attacker: C2 IP/port, created
    accounts, files dropped in suspicious locations, malware hashes. System files
    merely read or modified (/etc/passwd, /usr/bin/cat) are NOT IOCs and are
    discarded.
    """
    seen: set[str] = set()
    files_seen: set[str] = set()
    out: list[tuple[str, str, str]] = []

    def add(value, type_ioc, desc):
        if value and str(value) not in seen:
            seen.add(str(value))
            out.append((str(value), type_ioc, desc))

    def add_file(path, hashes, context):
        """One file = ONE IOC (cf. _ioc_file), hash preferred over path.

        Extra dedup on the PATH: the same file seen by two successive alerts
        (rescan) carries the same hash, so `add` would be enough; but a file
        rewritten between two scans changes hash while staying the same artefact,
        and we do not want two lines for that.
        """
        ioc = _ioc_file(path, hashes or {}, context)
        if ioc is None:
            return
        if path and str(path) in files_seen:
            return
        if path:
            files_seen.add(str(path))
        add(*ioc)

    for a in alerts:
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        data = raw.get("data", {})
        audit = data.get("audit", {})
        full_log = raw.get("full_log") or ""

        # Target of a /dev/tcp|udp redirection, in the log or the proctitle.
        # We only label it "C2" if it is OUTSIDE the estate: an internal target
        # (a whole /24 swept on port 22) is lateral movement / scanning, not a C2
        # — calling it a C2 polluted the threat intel and pointed a block at the
        # internal infrastructure.
        for text in (full_log, _decode_proctitle(full_log),
                      a.get("rule_desc") or ""):
            for ip, port in _RE_REVSHELL.findall(text):
                if not _ip_ioc_valid(ip):
                    continue
                if _ip_internal(ip):
                    add(ip, "ip-any", "Cible interne — connexion /dev/tcp "
                            f"(mouvement latéral / scan, port {port})")
                else:
                    add(ip, "ip-any",
                            f"IP C2 — cible reverse shell (port {port})")

        # Source IP of a network attack (e.g. web). Internal = pivot/lateral.
        srcip = a.get("srcip")
        if srcip and _ip_ioc_valid(srcip):
            add(srcip, "ip-any",
                    "IP source interne (pivot / mouvement latéral)"
                    if _ip_internal(srcip) else "IP source externe de l'attaque")

        # Account created/manipulated (useradd: dstuser + home/shell).
        dstuser = data.get("dstuser")
        if dstuser and dstuser not in _ACCOUNTS_SYSTEM and (
                data.get("home") or data.get("shell")):
            home = (data.get("home") or "?").rstrip(",")
            shell = (data.get("shell") or "?").rstrip(",")
            add(dstuser, "account",
                    f"Compte créé par l'attaquant (home {home}, shell {shell})")

        # Account creation seen in the auditd command (useradd/adduser):
        # catches the backdoor account even when the syslog 5902 alert (no uid,
        # no link) does not enter the incident. The account = last non-option
        # argument.
        m = _RE_USERADD.search(_decode_proctitle(full_log))
        if m and m.group(1) not in _ACCOUNTS_SYSTEM:
            add(m.group(1), "account", "Compte créé par l'attaquant (useradd)")

        # Windows account created by the attacker: event 4720
        # (targetUserName) or a "net user <name> /add" command line. Without
        # this, the creation of an AD backdoor (net user art-backdoor /add
        # /domain) was not an "account" IOC, so mitigate's deterministic net
        # (account created -> disable_user) never fired. Machine accounts ($)
        # discarded.
        wev = (data.get("win") or {}).get("eventdata") or {}
        wsys = (data.get("win") or {}).get("system") or {}
        tuser = wev.get("targetUserName")
        if (str(wsys.get("eventID") or "") == "4720" and tuser
                and not str(tuser).endswith("$")):
            add(tuser, "account", "Compte Windows créé par l'attaquant (4720)")
        mw = _RE_NETUSER_ADD.search(str(wev.get("commandLine") or full_log or ""))
        if mw and not mw.group(1).endswith("$"):
            add(mw.group(1), "account",
                    "Compte créé par l'attaquant (net user /add)")

        # File dropped in a suspicious location (dropped binary, webshell).
        file = (audit.get("file", {}) or {}).get("name") or a.get("entity")
        if _path_suspicious(file):
            add(file, "filename", "Fichier déposé (emplacement suspect)")

        # File quoted as an ARGUMENT of the command. The two fields above only
        # carry the binary loaded by the kernel: `insmod /tmp/rootkit.ko`
        # produced `/usr/bin/kmod`, `python3 /tmp/.implant.py` produced
        # `/usr/bin/python3`. The artefact actually dropped therefore appeared
        # in NO IOC of the case, although it is the first one the analyst looks
        # for and the only one they can hunt on the other hosts.
        # `add` and not `add_file`: with no hash at hand, reserving the path in
        # `files_seen` would prevent a later block (FIM, VT, YARA) from
        # publishing the SAME file carried by its hash — the more useful of the
        # two values.
        for path in _paths_argv(audit, full_log):
            add(path, "filename", "Fichier déposé en emplacement suspect "
                    "(cité en argument de commande)")

        # Windows offensive tool, executed or dropped outside the system
        # directories. Without this block, a purple-team exercise produced a
        # case with ONE single IOC (the created account): `mimikatz.exe`,
        # launched on the domain controller and quoted in a dozen alerts, was
        # not in it — although it is the artefact an analyst looks for first and
        # the only one they can hunt across the rest of the estate. Another case
        # of the same exercise had no IOC at all.
        for field in ("image", "targetFilename", "sourceImage"):
            path = _norm_win_path(wev.get(field))
            if _exe_windows_suspicious(path):
                add_file(path,
                                {"sha256": wev.get("sha256"),
                                 "sha1": wev.get("sha1"),
                                 "md5": wev.get("md5")},
                                "Exécutable lancé ou déposé hors des "
                                "répertoires système (Windows)")

        # YARA match (YARITRUST scanner). A case apart, on purpose: the
        # `_path_suspicious` filter does NOT apply here. Elsewhere a path only
        # becomes an indicator through its location, for want of anything
        # better — a signature scanner, on the other hand, has ALREADY qualified
        # the content. Filtering on the directory made the real IOCs disappear:
        # a webshell in /usr/local/www/ (pfSense) or in a /var/www/ outside the
        # list fell through, although that is precisely the file to look for.
        #
        # `data.file_path` is the REAL path on the scanned machine; the sshfs
        # mount prefix (/mnt/yaritrust/<host>_<ip>/) is stripped upstream. That
        # is the one to put in the case: an analyst must be able to go and look
        # at the file on the host concerned.
        yara = data.get("yara") or {}
        if yara or data.get("event_type") == "file_match":
            host = yara.get("scanned_host") or data.get("hostname") or "?"
            score = data.get("score")
            suffix = f" (score {score})" if score else ""
            # Name of the first YARA rule that matched: what says WHAT the
            # file is, and the only thing really reusable when hunting.
            reasons = data.get("reasons") or []
            rule = (reasons[0].get("message") or "").replace(
                "YARA match with rule ", "") if reasons else ""
            detail = f" — {rule}" if rule else ""
            # Normalised in both cases: `file_path` itself arrives prefixed on
            # the alerts predating the scanner fix.
            add_file(
                _path_target(data.get("file_path") or yara.get("scan_path")),
                {"sha256": data.get("sha256"), "sha1": data.get("sha1"),
                 "md5": data.get("md5")},
                f"Fichier détecté par YARA sur {host}{suffix}{detail}")

        # File judged malicious by VirusTotal. Same reason as for YARA not to
        # filter on the directory: the qualification comes from the engine.
        #
        # TWO conditions, learned from a purple-team exercise where two of the
        # three produced IOCs were pure noise:
        #
        #  1. VirusTotal must have RETURNED a maliciousness verdict. The block
        #     only tested the presence of a hash, so a `found=0, malicious=0`
        #     answer — VT does not even know the file — produced an IOC titled
        #     "Fichier signalé par VirusTotal". A hash unknown to VT is not an
        #     indicator of compromise.
        #  2. The target must be a FILE. Wazuh's VT integration follows the FIM
        #     events, registry included: `source.file` here was
        #     `HKEY_LOCAL_MACHINE\System\...\bam\State\...`, a registry key.
        #     A key has no content to submit for analysis, and the hash that
        #     comes with it designates no binary.
        vt_bloc = data.get("virustotal", {}) or {}
        vt = vt_bloc.get("source", {}) or {}
        if _vt_malicious(vt_bloc) and not _is_registry_key(vt.get("file")):
            add_file(vt.get("file"),
                            {"sha256": vt.get("sha256"), "sha1": vt.get("sha1"),
                             "md5": vt.get("md5")},
                            "Fichier signalé par VirusTotal "
                            f"({vt_bloc.get('malicious')} moteurs positifs)")

        # Suspicious file modified (FIM): here the directory matters, no engine
        # judged the content.
        sc = raw.get("syscheck", {})
        if _path_suspicious(sc.get("path")):
            add_file(sc.get("path"),
                            {"sha256": sc.get("sha256_after"),
                             "sha1": sc.get("sha1_after"),
                             "md5": sc.get("md5_after")},
                            "Fichier modifié dans un emplacement suspect (FIM)")
    return out


def _group_rules(alerts: list[dict]) -> list[tuple[str, dict]]:
    """Alerts grouped by rule, with a time window, in chronological order."""
    by: dict[str, dict] = {}
    for a in alerts:
        e = by.get(a["rule_id"])
        if e is None:
            by[a["rule_id"]] = {
                "level": a["rule_level"], "desc": a["rule_desc"] or "",
                "n": 1, "first": a["ts"], "last": a["ts"],
                "users": {a["srcuser"]} if a.get("srcuser") else set(),
                "entities": {a["entity"]} if a.get("entity") else set(),
                # Alerts of the group: the timeline re-extracts the IOCs from
                # them to link every event to its indicators (Graph tab).
                "alerts": [a]}
        else:
            e["n"] += 1
            e["alerts"].append(a)
            e["first"] = min(e["first"], a["ts"])
            e["last"] = max(e["last"], a["ts"])
            if a.get("srcuser"):
                e["users"].add(a["srcuser"])
            if a.get("entity"):
                e["entities"].add(a["entity"])
    return sorted(by.items(), key=lambda kv: kv[1]["first"])


def _uids_suspicious(alerts: list[dict]) -> set[str]:
    """UIDs under which the malicious activity fired (alerts >= MIN_LEVEL).

    Used to isolate the attacker's commands from the background noise. A SUID
    privesc keeps the real uid of the compromised account (only the euid goes to
    0): filtering on that uid therefore captures the WHOLE chain, root actions
    included.
    """
    uids: set[str] = set()
    for a in alerts:
        if a["rule_level"] < config.MIN_LEVEL:
            continue
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        uid = (raw.get("data", {}).get("audit", {}) or {}).get("uid")
        if uid is not None:
            uids.add(str(uid))
    # If a non-root account is compromised (the normal case: web service, uid
    # 33), we discard root: a SUID privesc keeps the real uid of the account, so
    # the attacker's root actions stay tagged with that uid. Keeping "0" would
    # only suck in every root daemon and the SOC response itself.
    non_root = uids - {"0"}
    return non_root or uids


# Commands emitted by the session/login machinery (systemd --user, gpg-agent,
# dbus), never by an attacker's shell. The same uid carries the legitimate
# session AND the attack: this filter discards the leftover login noise that
# would fall inside the attack window. Best-effort, anchored on the binary (not a
# mere mention) so as not to hide an attacker command that would name them.
_RE_NOISE_SESSION = re.compile(
    r"\b(?:gpgconf|gpg-agent|dbus-launch|dbus-update-activation-environment|"
    r"systemd-xdg-autostart-generator)\b"
    r"|/usr/lib/systemd/"
    r"|systemctl\s+--user\s+set-environment"
    r"|enable-ssh-support"       # gpg-agent config probe (ssh), login noise
    r"|^(?:systemd|30-systemd-envi)$",
    re.I)


# Windows execution noise: commands emitted by the endpoint machinery, never by
# the attacker. The `net1 user ...` child launched by the Wazuh agent (SCA,
# inventory collection) fired the same 92039 rules as an attacker's enumeration
# and filled the section. The parent is the discriminant: we only hide a command
# on what its PARENT is, not on its text.
_RE_NOISE_WIN_PARENT = re.compile(r"ossec-agent|wazuh-agent\.exe", re.I)
# Microsoft telemetry/maintenance, this one anchored on the called binary.
_RE_NOISE_WIN = re.compile(
    r"\b(?:CompatTelRunner|MpCmdRun|MpSigStub|TrustedInstaller|"
    r"consent|conhost)\.exe\b", re.I)


def _win_eventdata(raw: dict) -> dict:
    return ((raw.get("data", {}) or {}).get("win", {}) or {}).get("eventdata", {}) or {}


def _deswap_win(txt: str) -> str:
    r"""The eventdata fields arrive doubly escaped (`C:\\Windows`, `\"`) because
    of the double JSON encoding on the eventchannel side, and the redirections
    are HTML entities (`&gt;`, `&amp;`). Made readable for the analyst, without
    touching the stored values."""
    return html.unescape(txt.replace("\\\\", "\\").replace('\\"', '"'))


# `powershell -enc <base64>`: the payload is in UTF-16LE. Undecoded, the line
# says NOTHING to the analyst (and the attacker counts on it). The abbreviated
# forms PowerShell accepts run from `-e` to `-encodedcommand`.
_RE_ENCODEDCMD = re.compile(
    r"(-(?:e|en|enc|enco|encod|encode|encoded|encodedc|encodedco|encodedcom|"
    r"encodedcomm|encodedcomma|encodedcomman|encodedcommand)\s+)"
    r"([A-Za-z0-9+/=]{40,})", re.I)


def _decode_encodedcommand(cmd: str) -> str:
    """Replace the base64 payload of an `-EncodedCommand` by its text."""
    def repl(m):
        b64 = m.group(2)
        try:
            txt = base64.b64decode(b64 + "=" * (-len(b64) % 4)).decode("utf-16-le")
        except Exception:  # noqa: BLE001 — an undecodable blob stays as is
            return m.group(0)
        return f"{m.group(1)}<décodé> {' '.join(txt.split())}"
    return _RE_ENCODEDCMD.sub(repl, cmd)


def _users_suspicious_win(alerts: list[dict]) -> set[str]:
    """Windows accounts under which the malicious activity fired.

    Equivalent of `_uids_suspicious` on the eventchannel side. No exclusion
    analogous to root's: on Windows post-exploitation LEGITIMATELY runs as SYSTEM
    (service, scheduled task, PsExec), so discarding SYSTEM would erase the
    attack.
    """
    users: set[str] = set()
    for a in alerts:
        if a["rule_level"] < config.MIN_LEVEL:
            continue
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        ed = _win_eventdata(raw)
        u = ed.get("user") or ed.get("subjectUserName")
        if u:
            users.add(_deswap_win(str(u)))
    return users


def _cmds_windows(alerts: list[dict]) -> tuple[list[tuple], set[str]]:
    """(ts, command) rebuilt from Sysmon EID 1 / Security 4688.

    Windows counterpart of the auditd reconstruction: the "Commandes exécutées"
    section said "aucune commande" on EVERY Windows case, while the full command
    line sits in `data.win.eventdata.commandLine`. Also returns the accounts
    kept, for the scope sentence.
    """
    users = _users_suspicious_win(alerts)
    occ: list[tuple] = []
    for a in alerts:
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        ed = _win_eventdata(raw)
        if not ed:
            continue
        u = ed.get("user") or ed.get("subjectUserName")
        if users and (not u or _deswap_win(str(u)) not in users):
            continue
        parent = _deswap_win(str(ed.get("parentCommandLine")
                                 or ed.get("parentImage") or ""))
        if parent and _RE_NOISE_WIN_PARENT.search(parent):
            continue
        cmd = (ed.get("commandLine") or ed.get("processCommandLine")
               or ed.get("newProcessName") or ed.get("image") or "")
        cmd = _decode_encodedcommand(_deswap_win(str(cmd)).strip())
        if not cmd or _RE_NOISE_WIN.search(cmd):
            continue
        occ.append((a["ts"], cmd))
    return occ, users


def _clusters_linked_attack(occ: list[tuple], anchors: list, gap) -> list[tuple]:
    """Keep only the commands attached to the attack.

    `occ`: (ts, cmd) sorted by ts. We segment into clusters separated by a
    silence > `gap`, and keep only those that touch (within `gap`) a malicious
    alert (`anchors`, timestamps of the HIGH alerts). The session noise under the
    same uid, isolated by a longer silence, is discarded. Without an anchor we do
    not filter (we do not know where the attack is).
    """
    if not occ or not anchors:
        return occ

    def affects(cluster: list[tuple]) -> bool:
        return any(min(abs(t - a) for a in anchors) <= gap for t, _ in cluster)

    kept: list[tuple] = []
    cluster = [occ[0]]
    for prev, cur in zip(occ, occ[1:]):
        if cur[0] - prev[0] <= gap:
            cluster.append(cur)
        else:
            if affects(cluster):
                kept += cluster
            cluster = [cur]
    if affects(cluster):
        kept += cluster
    return kept


def _section_commands(alerts: list[dict]) -> str:
    """History of the attacker's commands: auditd (Linux) AND Sysmon EID 1 /
    Security 4688 (Windows), merged into a single chronology — a campaign case
    covers both operating systems.

    The proctitle (rule 80792, level 3) carries the full command line. By
    lowering ATTACH_MIN_LEVEL to 3, those alerts enter the incident: we unroll
    here the enumeration and the exploitation (find SUID, cat /etc/shadow,
    useradd, systemctl...) that the HIGH rules alone did not show.

    Two filters to show ONLY the attack, not the legitimate session of the same
    account: (1) temporal attachment — we keep only the commands forming a
    contiguous cluster around a malicious alert (`_clusters_linked_attack`),
    which discards the login init burst (gpg-agent, systemd generators);
    (2) categorical filter — the leftover session-machinery commands that fell
    inside the window (`_RE_NOISE_SESSION`). The uid of the compromised account
    already bounds the perimeter. Deterministic, local note.
    """
    uids = _uids_suspicious(alerts)
    anchors = [a["ts"] for a in alerts if a["rule_level"] >= config.MIN_LEVEL]
    gap = timedelta(seconds=config.COMMAND_CLUSTER_GAP_S)

    occ: list[tuple] = []
    for a in sorted(alerts, key=lambda x: x["ts"]):
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        audit = raw.get("data", {}).get("audit", {}) or {}
        if uids and str(audit.get("uid")) not in uids:
            continue
        cmd = _decode_proctitle(raw.get("full_log") or "").strip()
        if not cmd:
            cmd = str(audit.get("command") or "").strip()
        if not cmd or _RE_NOISE_SESSION.search(cmd):
            continue
        occ.append((a["ts"], cmd))

    occ_win, users_win = _cmds_windows(alerts)
    occ = sorted(occ + occ_win, key=lambda o: o[0])

    # Attachment to the attack, THEN dedup (a command seen both in the noise
    # AND in the attack must be kept with its attack ts).
    occ = _clusters_linked_attack(occ, anchors, gap)
    seen: set[str] = set()
    cmds: list[tuple] = []
    for ts, cmd in occ:
        if cmd in seen:
            continue
        seen.add(cmd)
        cmds.append((ts, cmd))

    if not cmds:
        return ("## Commandes exécutées\n\nAucune commande "
                "reconstituée (pas d'alerte d'audit de commande dans le "
                "périmètre).")
    accounts = [f"uid {u}" for u in sorted(uids)] + sorted(users_win)
    scope = (f"sous le(s) compte(s) compromis {', '.join(accounts)}" if accounts
              else "tous comptes (compte compromis non identifié)")
    lines = [
        "## Commandes exécutées",
        "",
        f"{len(cmds)} commandes distinctes reconstituées depuis la télémétrie "
        f"d'exécution ({scope}), rattachées à l'attaque, ordre chronologique :",
        "",
        "```",
    ]
    # Date included if the commands span several UTC days, otherwise the time
    # alone makes the chronological order ambiguous (same HH:MM from one day to
    # the next).
    days = {ts.astimezone(timezone.utc).date() for ts, _ in cmds}
    fmt = "%m-%d %H:%M:%S" if len(days) > 1 else "%H:%M:%S"
    for ts, cmd in cmds[:80]:
        lines.append(f"{ts.astimezone(timezone.utc):{fmt}}  {cmd[:300]}")
    if len(cmds) > 80:
        lines.append(f"... (+{len(cmds) - 80} autres)")
    lines.append("```")
    return "\n".join(lines)


def _fmt_interval(first, last) -> str:
    """Readable window. Adds the date (mm-dd) as soon as the interval crosses a
    UTC day — without it, `%H:%M:%S` alone made a multi-day span look reversed
    (e.g. `15:44 → 13:47`, end < start, when the last one is on the next day).
    first <= last is guaranteed by the min/max upstream."""
    fu = first.astimezone(timezone.utc)
    lu = last.astimezone(timezone.utc)
    if lu == fu:
        return f"{fu:%H:%M:%S}"
    if fu.date() == lu.date():
        return f"{fu:%H:%M:%S} → {lu:%H:%M:%S}"
    return f"{fu:%m-%d %H:%M:%S} → {lu:%m-%d %H:%M:%S}"


# Above this number of occurrences for a single rule, the count reflects
# repeated firings (e.g. one /dev/tcp write per swept target), not that many
# distinct events: we annotate it so the scale is not overestimated.
_THRESHOLD_BURST = 500


def _link_attack(tid: str) -> str:
    """ATT&CK URL of a technique. A sub-technique T1547.006 lives under
    `/techniques/T1547/006/`, not `/techniques/T1547.006/`."""
    base, _, under = tid.partition(".")
    return (f"https://attack.mitre.org/techniques/{base}/{under}/" if under
            else f"https://attack.mitre.org/techniques/{base}/")


def _section_mitre(alerts: list[dict]) -> str:
    """ATT&CK table of the case techniques (deterministic, not the LLM).

    What the RULES mapped, not the single technique kept at triage: triage
    returns only one (the one that carried its decision), and an exercise case
    was thereby summarised as "T1059.001 PowerShell" while the same alerts
    carried dcsync, golden ticket and pass-the-hash.

    The name and the tactic come from `rule.mitre` of the raw log (the columns
    only keep the ids and the tactics); order = first occurrence, so the table
    reads as the progression of the attack.
    """
    techs: dict[str, dict] = {}
    for a in alerts:
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        mitre = (raw.get("rule") or {}).get("mitre") or {}
        ids = list(mitre.get("id") or a.get("mitre_ids") or [])
        names = list(mitre.get("technique") or [])
        tactics = list(mitre.get("tactic") or a.get("mitre_tactics") or [])
        for i, tid in enumerate(ids):
            tid = str(tid).strip()
            if not tid:
                continue
            e = techs.setdefault(tid, {"name": "", "tactics": set(),
                                       "n": 0, "first": a["ts"]})
            # The id/technique lists run in parallel when the rule maps
            # several techniques; we only take the name if it faces the id.
            if not e["name"] and i < len(names):
                e["name"] = str(names[i]).strip()
            e["tactics"].update(str(t).strip() for t in tactics if t)
            e["n"] += 1
            e["first"] = min(e["first"], a["ts"])

    if not techs:
        return ("## Techniques MITRE ATT&CK\n\nAucune technique mappée par les "
                "règles déclenchées sur cet incident.")
    lines = [
        "## Techniques MITRE ATT&CK",
        "",
        f"{len(techs)} technique(s) mappée(s) par les règles Wazuh qui ont "
        "tiré, par ordre d'apparition :",
        "",
        "| Technique | Nom | Tactique(s) | Alertes |",
        "|:---|:---|:---|:---:|",
    ]
    for tid, e in sorted(techs.items(), key=lambda kv: (kv[1]["first"], kv[0])):
        name = e["name"] or "—"
        tac = ", ".join(sorted(e["tactics"])) or "—"
        lines.append(f"| [{tid}]({_link_attack(tid)}) | {name} | {tac} "
                      f"| {e['n']} |")
    return "\n".join(lines)


def _section_alerts(alerts: list[dict], agent_id: str) -> str:
    """Table of the Wazuh alerts of the case (deterministic, real values).

    Grouped by rule and ordered by first occurrence: the table reads as the
    chronology of the attack. "Log" column = Discover deep link (markdown
    reference at the bottom of the section: keeps the table compact and avoids
    the parentheses of the URL inside a cell).
    """
    lines = [
        "## Alertes Wazuh impliquées",
        "",
        f"{len(alerts)} alertes corrélées, regroupées par règle "
        "(ordre chronologique) :",
        "",
        "| Niveau | Règle | Occ. | Fenêtre UTC | Description | Log |",
        "|:---:|:---:|:---:|:---|:---|:---:|",
    ]
    refs = []
    for rid, e in _group_rules(alerts):
        fen = _fmt_interval(e["first"], e["last"])
        occ = f"{e['n']} ⚠️rafale" if e["n"] >= _THRESHOLD_BURST else str(e["n"])
        desc = (e["desc"][:78] + "…") if len(e["desc"]) > 78 else e["desc"]
        label = f"w-{rid}"
        lines.append(f"| {e['level']} | {rid} | {occ} | {fen} | {desc} "
                      f"| [🔎][{label}] |")
        refs.append(f"[{label}]: <{_link_wazuh(agent_id, rid, e['first'], e['last'])}>")
    lines.append("")
    lines.extend(refs)          # reference definitions of the Discover links
    return "\n".join(lines)


def _type_ioc_value(value: str) -> str:
    """IOC type deduced from the value alone (for an IOC already on the case
    whose type we do not have at hand). Best-effort, aligned on the types
    produced by `_iocs`: hash, ip, domain, otherwise filename."""
    v = value.strip()
    if re.fullmatch(r"[0-9a-fA-F]{64}", v):
        return "sha256"
    if re.fullmatch(r"[0-9a-fA-F]{40}", v):
        return "sha1"
    if re.fullmatch(r"[0-9a-fA-F]{32}", v):
        return "md5"
    if re.fullmatch(r"\d{1,3}(?:\.\d{1,3}){3}", v):
        return "ip-src"
    if "\\" not in v and "/" not in v and "." in v and " " not in v:
        return "domain"
    return "filename"


def _iocs_of_case(case, case_id: int, alerts: list[dict]) -> list[tuple[str, str, str]]:
    """AUTHORITATIVE IOCs of the case = those really laid in the IOC tab.

    The report must show EXACTLY the same list as the IOC section of the case,
    including the IOCs inherited from an earlier burst (a campaign case is
    updated several times: the timeline and IOC tab accumulate, while `_iocs`
    recomputed on the alerts of the current run alone would show fewer). So we
    read the IOC tab as the source of truth. The type and description of the
    current burst win (fresher); for an inherited IOC with no known type, we
    deduce it from the value. Order: IOCs of the current burst first (order of
    `_iocs`), then the inherited remainder.

    Falls back on `_iocs(alerts)` if the tab is unreadable: never less than what
    the code knows how to extract.
    """
    current = _iocs(alerts)
    type_by_value = {v: t for v, t, _ in current}
    desc_by_value = {v: d for v, _, d in current}
    try:
        d = case.list_iocs(case_id).get_data() or {}
        tab = [(i.get("ioc_value"), i.get("ioc_description") or "")
               for i in (d.get("ioc") or []) if i.get("ioc_value")]
    except Exception as e:  # noqa: BLE001
        log.debug("reading the IOC tab of case #%s for the report: %s",
                  case_id, e)
        return current
    if not tab:
        return current
    order = [v for v, _, _ in current]
    rank = {v: n for n, v in enumerate(order)}
    def key(item):
        return rank.get(item[0], len(order))
    out: list[tuple[str, str, str]] = []
    for value, desc_tab in sorted(tab, key=key):
        type_ioc = type_by_value.get(value) or _type_ioc_value(value)
        # Description of the current burst if available (the most up to date),
        # otherwise the one of the case.
        desc = desc_by_value.get(value) or desc_tab
        out.append((value, type_ioc, desc))
    return out


def _section_iocs(alerts: list[dict],
                  iocs: list[tuple[str, str, str]] | None = None) -> str:
    """Table of the extracted IOCs (deterministic). Local note: real values.

    `iocs` given = authoritative list of the case IOC tab (cf. `_iocs_of_case`)
    so the report shows EXACTLY the same thing. Absent = recomputed on the alerts
    (case of a rendering outside a case)."""
    if iocs is None:
        iocs = _iocs(alerts)
    if not iocs:
        return "## Indicateurs de compromission (IOC)\n\nAucun IOC extractible " \
               "automatiquement des champs d'alerte."
    lines = [
        "## Indicateurs de compromission (IOC)",
        "",
        "| Type | Valeur | Contexte |",
        "|:---|:---|:---|",
    ]
    for value, type_ioc, desc in iocs:
        v = value.replace("|", "\\|")
        lines.append(f"| {type_ioc} | `{v}` | {desc} |")
    return "\n".join(lines)


# Readable rendering of a remediation status.
#
# NEVER display "✅" on anything other than a report from the agent. The
# active-response channel is fire-and-forget: at the moment of the call, all we
# know is that the API took the command. The old label "✅ exécuté" was attached
# to that mere acknowledgement, and a purple-team exercise report told the
# analyst that dozens of System32 binaries of a domain controller had been
# quarantined — the script had refused every one of them. A report that lies is
# worse than an incomplete report.
_STATUS_REMED = {
    "sent": "📤 commande émise (effet non encore confirmé)",
    "confirmed": "✅ confirmé par l'agent",
    "no_effect": "⚪ sans effet (rien à faire sur cette cible)",
    "agent_refused": "🛑 refusé par le garde-fou de l'agent",
    "dry_run": "🟡 simulé (dry-run)",
    "no_channel": "📄 documenté (manuel)",
    "failed": "❌ échec",
    "canceled": "↩️ annulé (défait)",
}


def _section_remediations(conn, incident_id: int, triage: dict) -> str:
    """Recap of the remediations REALLY executed (mitigations table).

    Replaces the old "proposed" list: the actions are now launched automatically
    when the case is opened; we report what was done, not what could be.
    """
    rows = conn.execute(
        "SELECT action, target, status FROM mitigations WHERE incident_id = %s "
        "ORDER BY id", (incident_id,)).fetchall()
    lines = ["## Remédiations"]

    if not rows:
        remed = [a for a in triage.get("actions", [])
                 if a in LABEL_ACTION and a.startswith("propose_")]
        lines.append("")
        if remed:
            lines.append("Aucune remédiation automatique n'a pu s'appliquer "
                          "(pas de cible exploitable). Actions décidées au "
                          "triage :")
            lines += [f"- {LABEL_ACTION.get(a, a)}" for a in remed]
        else:
            lines.append("Aucune remédiation à exécuter pour cet incident.")
        return "\n".join(lines)

    lines += [
        "",
        "Actions lancées automatiquement par le soc-agent à l'ouverture du "
        "case. Procédures d'annulation détaillées dans le répertoire "
        "« Remédiations ».",
        "",
        "Le statut est celui **rapporté par l'agent**, pas celui de l'appel "
        "d'API : le canal d'active response ne renvoie pas le code de retour du "
        "script, donc une commande partie n'est pas une action faite. Une ligne "
        "« commande émise » qui ne se confirme pas signale un script mort avant "
        "son compte rendu, ou un agent qui ne remonte pas "
        "`active-responses.log`.",
        "",
        "| Action | Cible | Statut |",
        "|:---|:---|:---:|",
    ]
    for r in rows:
        label = LABEL_ACTION.get(r["action"], r["action"])
        status = _STATUS_REMED.get(r["status"], r["status"])
        lines.append(f"| {label} | `{r['target']}` | {status} |")

    refused = [r for r in rows if r["status"] == "agent_refused"]
    if refused:
        lines += [
            "",
            f"> **{len(refused)} action(s) refusée(s) par un garde-fou de "
            "l'agent.** Le garde-fou a fait son travail, mais le soc-agent a "
            "visé une cible qu'il n'aurait pas dû retenir : la résolution de "
            "cibles est à revoir pour ce type d'incident.",
        ]
    return "\n".join(lines)


def _note_fp(triage: dict, rule: dict | None) -> str:
    """Analysis note of a false positive, with the whitelist explanation.

    Pure: `rule` is the whitelist_rules row matching the signature of the
    incident (or None), supplied by the caller. Testable without a database.
    """
    lines = [
        "# Analyse — Faux positif",
        "",
        "## Justification",
        triage["reason"],
        "",
        "## Whitelist",
    ]
    if rule:
        state = "active" if rule["active"] else "inactive"
        lines += [
            f"Une exception **{state}** ({rule['source']}) couvre désormais cette "
            "signature — les alertes identiques seront écartées avant analyse :",
            "",
            f"```json\n{json.dumps(rule['match_all'], ensure_ascii=False, indent=2)}\n```",
            "",
            f"Motif : {rule['reason']}",
        ]
    else:
        lines.append("Pas encore d'exception : ce faux positif n'a pas atteint "
                      "le seuil de récurrence, ou sa signature est trop large "
                      "pour une whitelist automatique sûre.")
    return "\n".join(lines)


def _rule_whitelist(conn, alerts: list[dict]) -> dict | None:
    """whitelist_rules row matching the signature of the incident."""
    raws = [a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
            for a in alerts]
    signature = _signature(raws)
    if not signature:
        return None
    return conn.execute(
        "SELECT match_all, reason, source, active FROM whitelist_rules "
        "WHERE signature = %s", (_canonical(signature),)).fetchone()


# Sensor families, spotted through the rule groups they produce. Used to tell
