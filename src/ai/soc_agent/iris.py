def _active_sensors(conn, agent_id: str) -> str:
    """"Telemetry available on this host" line, from the rule groups really
    emitted by the agent over the recent window. Factual: anchors the "coverage"
    section of the report so it is not invented."""
    rows = conn.execute(
        "SELECT DISTINCT unnest(rule_groups) g FROM alerts "
        "WHERE agent_id = %s AND ts >= now() - interval '7 days'",
        (agent_id,)).fetchall()
    seen = {r["g"] for r in rows}
    states = [f"{label}={'présent' if seen & groups else 'ABSENT'}"
             for label, groups in _SENSORS]
    return "télémétrie disponible sur cet hôte : " + ", ".join(states)


# Accounts present on every host: linking two incidents on them means nothing.
_ACCOUNTS_GENERIC = {"root", "admin", "administrator", "www-data", "nobody",
                       "daemon", "sync", "postgres", "mysql", "-", ""}

# The fleet runs in LXC containers; auditd runs on the Proxmox host (agent pve)
# and sees the execve of ALL the containers. The `soc-audit-enrich` enricher tags
# every record with the originating container (`lxc_ct=<name>`, cf.
# src/wazuh/agents/pve/). We extract it here so the case says "jellyfin" and not
# "pve". Real values, local note — never sent to the LLM (host name).
_LXC_CT = re.compile(r"lxc_ct=([A-Za-z0-9_.-]+)")


def _containers(alerts: list[dict]) -> list[str]:
    """Originating LXC containers, extracted from the enriched full_log. Ignores
    host and unknown (short exec not resolved). Empty if the host is not the pve
    agent."""
    seen: set[str] = set()
    for a in alerts:
        raw = a.get("raw")
        raw = raw if isinstance(raw, dict) else json.loads(raw) if raw else {}
        for ct in _LXC_CT.findall(str(raw.get("full_log", ""))):
            if ct not in ("host", "unknown"):
                seen.add(ct)
    return sorted(seen)


def _incidents_linked(conn, incident: dict) -> list[dict]:
    """IRIS cases open on OTHER agents sharing a strong entity (same IP, same
    file, same account) within a +/-ENTITY_GAP window around this one.

    The main correlation is partitioned per agent (correlate.py) — a pivot from
    one host to another is therefore invisible by construction. This pass catches
    it after the fact WITHOUT merging: we flag the link to the analyst. On
    2026-07-29 the bookstack -> jellyfin pivot appeared in no case at all.

    Only the incidents that have an IRIS case are returned: the section sends the
    analyst to a case they can open, not to an internal id of the soc-agent
    database they cannot consult anywhere. The case of the present incident is
    excluded — the campaign merge (`_merge_campaign`) puts several incidents,
    other hosts included, on the same case."""
    margin = timedelta(minutes=config.ENTITY_GAP_MINUTES)
    traits = conn.execute(
        "SELECT DISTINCT srcip, entity, srcuser FROM alerts WHERE incident_id=%s",
        (incident["id"],)).fetchall()
    # Source IP and file are strong links. The ACCOUNT is not: `root` (or
    # www-data, admin...) exists on every host — linking on it would bring every
    # incident together. So we discard the generic accounts, and keep the generic
    # shells already excluded on the correlation side.
    values = {t["srcip"] for t in traits if t["srcip"]}
    values |= {t["entity"] for t in traits
                if t["entity"] and not correlate.generic_entity(t["entity"])}
    values |= {t["srcuser"] for t in traits
                if t["srcuser"] and t["srcuser"].lower() not in _ACCOUNTS_GENERIC}
    if not values:
        return []
    items = list(values)
    rows = conn.execute(
        """SELECT DISTINCT i.id, i.agent_name, i.iris_case_id,
                  a.srcip, a.entity, a.srcuser
             FROM incidents i JOIN alerts a ON a.incident_id = i.id
            WHERE i.id <> %s AND i.agent_id <> %s
              AND i.iris_case_id IS NOT NULL
              AND i.iris_case_id IS DISTINCT FROM %s
              AND i.last_seen >= %s AND i.first_seen <= %s
              AND (a.srcip = ANY(%s) OR a.entity = ANY(%s) OR a.srcuser = ANY(%s))
            ORDER BY i.id""",
        (incident["id"], incident["agent_id"], incident.get("iris_case_id"),
         incident["first_seen"] - margin, incident["last_seen"] + margin,
         items, items, items)).fetchall()
    # Grouping by CASE: a campaign case carries several incidents, it must
    # appear only once — with every host it covers.
    by_case: dict[int, dict] = {}
    for r in rows:
        shared = next((v for v in (r["srcip"], r["entity"], r["srcuser"])
                        if v and v in values), None)
        if not shared:
            continue
        e = by_case.setdefault(r["iris_case_id"],
                                {"case_id": r["iris_case_id"],
                                 "agents": set(), "entities": set()})
        e["agents"].add(r["agent_name"] or "?")
        e["entities"].add(shared)
    return sorted(by_case.values(), key=lambda e: e["case_id"])


def _link_case(case_id: int) -> str:
    """URL of the IRIS case. Relative on purpose: the note is read INSIDE IRIS,
    and `config.IRIS_URL` is the server loopback (127.0.0.1:8443) — an absolute
    link built on it would be dead for the analyst, who reaches IRIS through the
    estate address."""
    return f"/case?cid={case_id}"


def _section_cases_linked(linked: list[dict]) -> str:
    """Local note (real values). Built in Python, NEVER sent to the LLM: the
    hostnames of the other hosts do not leave for the cloud."""
    if not linked:
        return ""
    lines = ["## Cases liés (autres hôtes)", "",
              "Rapprochement par entité partagée, hors du cloisonnement par "
              "agent — possible mouvement latéral ou campagne à investiguer :",
              "",
              "| Case | Hôte(s) | Entité commune |",
              "|:---:|:---|:---|"]
    for l in linked:
        agents = ", ".join(f"**{a}**" for a in sorted(l["agents"]))
        # A campaign often shares a dozen entities: past 3 the cell becomes
        # unreadable and adds nothing — the linked case can be opened.
        ents = sorted(l["entities"])
        ent = ", ".join(f"`{e}`" for e in ents[:3])
        if len(ents) > 3:
            ent += f" (+{len(ents) - 3})"
        lines.append(f"| [#{l['case_id']}]({_link_case(l['case_id'])}) "
                      f"| {agents} | {ent} |")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------
# Vulnerability exposure of the affected machine
# --------------------------------------------------------------------------
#
# Why this section exists: a case says what the attacker DID, never what they
# could have done. Yet the same intrusion on an up-to-date host and on a host
# dragging fourteen critical CVEs does not call for the same follow-up — in the
# second case, remediating the incident does not close the door. The analyst had
# the information (VOC dashboard) but had to go and fetch it, on the right
# machine, cross-referencing the asset priority themselves.
#
# Three writing rules, strictly held:
#
#  1. What is CERTAIN and what is LIKELY do not mix. A CVE quoted in a command of
#     the attacker is a fact; a critical CVE open on a machine where T1068 is
#     seen is a lead. Both appear, under different titles, with the nuance
#     written down.
#  2. "No known vulnerability" and "never inventoried" are two opposite
#     statements. The second is a blind spot and must be said — the same lesson
#     as the "telemetry available" line of the reports.
#  3. None of this leaves for the model in clear. Only a numeric summary, with no
#     host or package name, is given to it as a confidence metadata.

def _link_cve(cve: str) -> str:
    return f"https://nvd.nist.gov/vuln/detail/{cve}"


def _package(name: str) -> str:
    """Package name shortened for a table cell.

    On Windows, `package.name` is the full OS label, version included
    ("Microsoft Windows Server 2022 Standard Evaluation 10.0.20348.587"):
    repeated over ten rows next to a Version column that says the same thing, it
    drowns the CVE column, which is the useful information.
    """
    name = str(name or "—")
    return name if len(name) <= 46 else name[:45] + "…"


def _table_cve(lines: list[dict], with_age: bool = True) -> list[str]:
    """Markdown table of vulnerabilities. Columns stable from one block to the
    next so the analyst does not re-read the header at every section."""
    head = ["| CVE | Sévérité | CVSS | Paquet | Version |"
            + (" Ouverte depuis |" if with_age else ""),
            "|:---|:---|---:|:---|:---|" + ("---:|" if with_age else "")]
    for v in lines:
        age = f" {v['age_days']:.0f} j |" if with_age else ""
        head.append(
            f"| [{v['cve']}]({_link_cve(v['cve'])}) "
            f"| {(v['severity'] or 'non classée').capitalize()} "
            f"| {v['base_score'] if v['base_score'] is not None else '—'} "
            f"| `{_package(v['package'])}` | {v['version'] or '—'} |{age}")
    return head


def _exposure_note(conn, incident: dict, alerts: list[dict]) -> str:
    """"Vulnerability exposure" note of the machine of the case.

    Built in Python from the VOC journal (`soc_agent.vulns`): real values, no
    call to the model. Always returns a note — including when the machine was
    never inventoried, a case where the absence of data IS the information.
    """
    from . import vulns   # deferred import: vulns imports assets, not iris.

    agent_id = str(incident["agent_id"])
    expo = vulns.exposure(conn, agent_id)
    link = vulns.incident_link(conn, agent_id, alerts, expo)

    lines = [f"# {EXPOSURE_TITLE}", "",
              f"Machine **{incident.get('agent_name') or agent_id}** "
              f"(agent {agent_id}), "
              f"priorité **P{expo['priority']}** "
              f"({expo['role'] or 'rôle non déclaré'}).", ""]

    if not expo["covered"]:
        lines += [
            "> ⚠️ **Cette machine n'a jamais été inventoriée** par le module "
            "Vulnerability Detection de Wazuh. Il n'y a donc aucune donnée de "
            "vulnérabilité à son sujet — ce qui n'est **pas** la même chose que "
            "« aucune vulnérabilité ». Causes usuelles : système d'exploitation "
            "absent du feed CTI (BSD, appliance), ou `syscollector` muet sur "
            "l'agent.",
            "",
            "Vérifier avec `python -m soc_agent.vulns --agent "
            f"{agent_id}` et l'inventaire de paquets côté API Wazuh "
            "(`/syscollector/<agent>/packages`).",
        ]
        return "\n".join(lines) + "\n"

    # --- Score and distribution -------------------------------------------
    sev_readable = {"critical": "Critical", "high": "High", "medium": "Medium",
                   "low": "Low", "": "non classée"}
    distribution = ", ".join(
        f"**{n}** {sev_readable.get(s, s)}"
        for s, n in sorted(expo["by_severity"].items(),
                           key=lambda kv: -vulns.weight(kv[0])))

    lines += [
        f"| | |", "|---|---|",
        f"| **Score d'exposition** | **{expo['score']}/100** — "
        f"exposition {expo['level']} |",
        f"| **Vulnérabilités ouvertes** | {expo['total']} ({distribution}) |",
        f"| **Hors délai de correction** | {expo['outside_sla_total']} |",
        f"| **Plus ancienne ouverte** | {expo['oldest_days']:.0f} jours |",
        (f"| **Corrigées sur 90 jours** | {expo['fixed_90d']} "
         f"(délai moyen {expo['mttr_days']} j) |"
         if expo["mttr_days"] is not None
         else f"| **Corrigées sur 90 jours** | {expo['fixed_90d']} |"),
        "",
        # The score is log-compressed and weighted: without this sentence a
        # reader would take it for a percentage of vulnerable machines or for an
        # audit mark. It also has to say that it saturates, otherwise two
        # machines at 100 would look equivalent.
        f"Le score agrège les vulnérabilités ouvertes pondérées par leur "
        f"sévérité (charge {expo['charge']}), multipliées par le facteur de "
        f"priorité de l'asset (×{expo['priority_factor']}), sur une échelle "
        f"logarithmique. Il sert à **classer** les machines entre elles, pas à "
        f"mesurer un risque absolu : au-delà du plafond il sature, et ce sont "
        f"alors les compteurs ci-dessus qui départagent.",
        "",
    ]

    # The journal cannot measure a delay longer than its own existence. While it
    # is young, "0 out of SLA" and "oldest: 3 days" are exact and misleading: they
    # describe how long we have been measuring, not the state of the estate.
    # Without this callout, a reader would see an up-to-date estate when it may
    # be dragging CVEs from 2019.
    young = expo.get("journal_days")
    if young is not None and young < 30:
        lines += [
            f"> ℹ️ **Le suivi VOC n'a que {young:.0f} jour(s) d'historique.** "
            f"L'ancienneté et le retard se comptent depuis la première "
            f"observation par AURA, pas depuis la publication de la CVE : "
            f"« {expo['oldest_days']:.0f} jours » et "
            f"« {expo['outside_sla_total']} hors délai » mesurent ici la durée de "
            f"la mesure, **pas** l'état réel du parc. Ces deux chiffres ne "
            f"deviennent significatifs qu'au-delà du premier seuil de SLA "
            f"applicable. Les compteurs par sévérité, eux, sont valables "
            f"immédiatement.",
            "",
        ]

    # --- Link with THIS case ----------------------------------------------
    if link["confirmed"]:
        lines += [
            "## Vulnérabilités citées dans l'incident",
            "",
            "Ces CVE apparaissent **littéralement** dans les évènements du case "
            "(ligne de commande, nom de fichier, requête) **et** sont ouvertes "
            "sur cette machine. C'est le seul rapprochement certain entre "
            "l'incident et l'exposition : ce que l'attaquant visait était "
            "effectivement présent ici.",
            "",
        ] + _table_cve(link["confirmed"]) + [
            "",
            "**Conséquence directe** : remédier l'incident ne suffit pas. Tant "
            "que ces paquets ne sont pas corrigés, le même accès reste "
            "reproductible.",
            "",
        ]

    if link["quoted_not_open"]:
        lines += [
            "## Vulnérabilités citées mais non ouvertes ici",
            "",
            "CVE mentionnées dans les évènements du case, mais absentes de "
            "l'inventaire de cette machine : tentative contre une version non "
            "vulnérable, reconnaissance à l'aveugle, ou vulnérabilité déjà "
            "corrigée depuis. C'est une information sur la MÉTHODE de "
            "l'attaquant, pas sur l'exposition de l'hôte.",
            "",
            ", ".join(f"[{c}]({_link_cve(c)})"
                      for c in link["quoted_not_open"]),
            "",
        ]

    if link["possible_vectors"]:
        lines += [
            "## Vecteurs possibles (hypothèse, non démontrée)",
            "",
            f"L'incident porte une ou des techniques d'exploitation "
            f"({', '.join(link['exploit_techniques'])}) et cette machine a des "
            f"vulnérabilités graves ouvertes. **Aucun élément du case ne relie "
            f"ces CVE à l'attaque** : elles sont listées parce qu'un analyste "
            f"qui cherche par où l'accès a été obtenu doit les avoir sous les "
            f"yeux, pas parce qu'elles ont été exploitées.",
            "",
        ] + _table_cve(link["possible_vectors"]) + [""]

    # --- Patching delay ---------------------------------------------------
    if expo["outside_sla"]:
        top = expo["outside_sla"][:config.VOC_MAX_CVE_REPORT]
        lines += [
            "## Vulnérabilités hors délai",
            "",
            f"{expo['outside_sla_total']} vulnérabilité(s) ouverte(s) au-delà du "
            f"délai attendu pour leur sévérité sur un asset P{expo['priority']}"
            + (f" — les {len(top)} plus en retard :" if len(top) < expo['outside_sla_total']
               else " :"),
            "",
            "| CVE | Sévérité | Paquet | Ouverte depuis | Délai | Retard |",
            "|:---|:---|:---|---:|---:|---:|",
        ] + [
            f"| [{v['cve']}]({_link_cve(v['cve'])}) "
            f"| {(v['severity'] or 'non classée').capitalize()} "
            f"| `{_package(v['package'])}` | {v['age_days']:.0f} j "
            f"| {v['sla_days']} j | **+{v['overdue_days']:.0f} j** |"
            for v in top
        ] + [""]

    # --- Fallback: nothing specific to the case ---------------------------
    if not (link["confirmed"] or link["possible_vectors"]
            or expo["outside_sla"]):
        lines += [
            "## Pires vulnérabilités ouvertes",
            "",
            "Aucune CVE n'est citée dans les évènements de ce case et aucune "
            "vulnérabilité n'est hors délai : **rien ne rattache cet incident à "
            "l'exposition de la machine**. Le contexte reste utile pour évaluer "
            "ce qu'une compromission d'ici permettrait ensuite.",
            "",
        ] + _table_cve(expo["worst"]) + [""]

    lines += [
        "---",
        "",
        f"Source : module Vulnerability Detection de Wazuh, journalisé par "
        f"`soc_agent.vulns` (index `{config.VOC_INDEX_PREFIX}-*`, dashboard "
        f"VOC). Les délais de correction sont des objectifs de service internes "
        f"définis par sévérité et priorité d'asset, pas une norme externe. Le "
        f"feed indique ce que les distributions publient : il ne dit **rien** "
        f"de l'exploitabilité réelle ni de l'exposition réseau du service "
        f"concerné.",
    ]
    return "\n".join(lines) + "\n"


def _set_exposure(case, case_id: int, conn, incident: dict,
                      alerts: list[dict]) -> None:
    """Lay down the exposure note. Best-effort: the VOC is an enrichment, its
    unavailability must never prevent a case from opening."""
    try:
        _set_note(case, case_id, EXPOSURE_TITLE,
                    _exposure_note(conn, incident, alerts),
                    directory=EXPOSURE_DIR)
    except Exception as e:  # noqa: BLE001
        log.warning("exposure note of case #%s: %s", case_id, e)


def _exposure_summary(conn, agent_id: str, alerts: list[dict]) -> str:
    """Exposure line intended for the MODEL, as a trusted metadata.

    Deliberately numeric and anonymous: no host name, no package name, no
    version. CVE identifiers do go through — they are public references, and they
    are precisely the information that lets the model link an exploitation
    command to a vulnerability really present. Without this line, the report used
    to write "nothing allows us to know whether the machine was vulnerable" while
    the SOC knew.
    """
    try:
        from . import vulns
        expo = vulns.exposure(conn, str(agent_id))
        if not expo["covered"]:
            return ("exposition aux vulnérabilités : machine JAMAIS "
                    "inventoriée (aucune donnée — ne pas conclure qu'elle est "
                    "à jour)")
        link = vulns.incident_link(conn, str(agent_id), alerts, expo)
        bout = (f"exposition aux vulnérabilités : score {expo['score']}/100 "
                f"({expo['level']}), {expo['total']} ouvertes dont "
                f"{expo['critical_count']} critical et {expo['high_count']} high, "
                f"{expo['outside_sla_total']} hors délai")
        if link["confirmed"]:
            bout += (" ; CVE citées dans l'incident ET ouvertes sur cet hôte : "
                     + ", ".join(v["cve"] for v in link["confirmed"]))
        return bout
    except Exception as e:  # noqa: BLE001
        log.debug("exposure summary of agent %s: %s", agent_id, e)
        return "exposition aux vulnérabilités : non disponible"


def _note_tp(conn, incident: dict, triage: dict, alerts: list[dict],
             iocs: list[tuple[str, str, str]] | None = None) -> str:
    """Analysis report of a true positive. Calls the LLM for the narrative.

    `iocs` = authoritative list of the case IOC tab (`_iocs_of_case`): the report
    then displays the SAME list as the IOC section of the case. Absent =
    recomputed on the alerts."""
    system = (PROMPTS / "report.md").read_text()

    # Same pseudonymisation as at triage, tokens reused (persisted map): nothing
    # sensitive leaves for the cloud, and the answer is rehydrated.
    anon = Anonymizer(load_map(conn, incident["id"]))
    inc_a, alerts_to, forbidden = anonymize(anon, incident, alerts)
    # Report = less rushed than triage: we show the whole chain to the model (up
    # to 20 rules) for an analysis that forgets no step.
    body = render(inc_a, alerts_to, max_rules=20)
    # Trusted SOC metadata (agent_id + group names, nothing sensitive): tells the
    # model which sensors existed, to anchor the coverage section.
    telemetry = _active_sensors(conn, incident["agent_id"])
    # Second trusted metadata: the exposure of the host, in numbers and CVEs (no
    # host or package name — cf. `_exposure_summary`). It keeps the report from
    # concluding "impossible to know whether the machine was vulnerable" while
    # the SOC has the inventory.
    exposure = _exposure_summary(conn, incident["agent_id"], alerts)
    user = (f"=== DEBUT INCIDENT (données non fiables) ===\n{body}\n"
                   "=== FIN INCIDENT ===\n\n"
                   f"Métadonnées SOC de confiance (non issues des logs) :\n"
                   f"{telemetry}\n{exposure}\n\nRédige le rapport.")

    try:
        # Leak scan on the incident data only: the system prompt (report.md) is
        # a constant dev template, with no customer data.
        check_leak(user, forbidden)
        report, _ = completion(system, user,
                                max_tokens=config.REPORT_MAX_TOKENS,
                                usage="report",
                                incident_id=incident["id"])
        save_map(conn, incident["id"], anon.mapping)
    except Exception as e:  # noqa: BLE001 — the case must be created even
        # without the LLM
        log.warning("LLM report unavailable (#%s): %s", incident["id"], e)
        report = {}
    # DeepSeek does not guarantee the keys of the schema: we tolerate absences.
    #
    # The fallback puts the SAME sentence in `resume` and in `analyse` — that is
    # unavoidable, we only have `triage.reason`. But it must not pass itself off
    # as a report: a purple-team exercise case displayed two identical sections
    # without flagging anything, and the analyst could not know they were reading
    # a fallback rather than an analysis. `degraded` triggers the warning banner
    # further down, AND prevents overwriting an already written report.
    degraded = "analyse" not in report
    report.setdefault("resume", triage["reason"])
    report.setdefault("analyse", triage["reason"])
    # Rehydration: the tokens become the real values again for the analyst. Then
    # correction of the model's recurring accent typos.
    for key in ("resume", "analyse"):
        report[key] = _fix_accents(rehydrate(report[key], anon.mapping))

    cts = _containers(alerts)
    lines = ["# Rapport d'analyse — Vrai positif", ""]
    # No more technique in the header: triage returns only ONE, the one that
    # carried its decision, and it is not even always in the rule mapping (case
    # 129: header T1098, ATT&CK table without T1098). The ATT&CK coverage is the
    # "Techniques MITRE ATT&CK" section, built on what the rules really mapped.
    # `triages.mitre` is still traced in the database.
    # Container attribution: the agent is the Proxmox host (pve); the real
    # theatre is the LXC container resolved by the auditd enricher.
    if cts:
        lines.append(f"**Conteneur(s) concerné(s)** : {', '.join(cts)} "
                      f"(exécution vue par l'auditd de l'hôte {incident['agent_name']})")
    if degraded:
        lines += [
            "",
            "> ⚠️ **Rapport dégradé — l'analyse LLM n'a pas abouti.** Les deux "
            "sections ci-dessous reprennent la justification du triage, faute "
            "de mieux. Il n'y a donc PAS eu de reconstitution de la chaîne "
            "d'attaque ici : voir la table des alertes et les IOC plus bas. "
            "Cause la plus fréquente : budget de tokens épuisé par le "
            "raisonnement du modèle (`REPORT_MAX_TOKENS`).",
        ]
    lines += [
        "",
        "## Résumé",
        report["resume"],
        "",
        "## Analyse",
        report["analyse"],
        "",
    ]
    lines += [
        _section_cases_linked(_incidents_linked(conn, incident)),
        _section_commands(alerts),
        "",
        _section_alerts(alerts, incident["agent_id"]),
        "",
        _section_iocs(alerts, iocs),
        "",
        _section_mitre(alerts),
        "",
        _section_remediations(conn, incident["id"], triage),
        "",
        _section_remediation_outside_scope(triage, alerts),
    ]
    return "\n".join(lines)


