# --------------------------------------------------------------------------
# Severity of the IRIS case
# --------------------------------------------------------------------------
#
# A queue of cases where everything is "Low" cannot be sorted. IRIS sets 4 (Low)
# by default at creation and its `add_case` API does not expose the severity: it
# is set afterwards, through `/manage/cases/update/<id>` (`case_severity_id`).
#
# TRAP: the ids of the IRIS scale do NOT follow the order of gravity —
# 3=Informational, 4=Low, 1=Medium, 5=High, 6=Critical, 2=Unspecified. Any
# mapping written on the ids would be wrong ("severity 2" = Unspecified, not
# Low). So we work on the NAMES, and resolve the id at runtime from the server:
# another IRIS deployment may well number them differently.
SEV_INFO, SEV_LOW, SEV_MEDIUM = "Informational", "Low", "Medium"
SEV_HIGH, SEV_CRITICAL = "High", "Critical"

# EXACT name of the field expected by `/manage/cases/update/<id>`.
# `case_severity_id` — the name one guesses from `case_classification_id` — is
# accepted, answers "updated"... and changes nothing. Checked in the database:
# only `severity_id` really writes `cases.severity_id`.
#
# No API endpoint READS the severity back (neither `/manage/cases/<id>`, nor
# `/manage/cases/list`, nor `/case/summary`): a rename of that field in a future
# IRIS version would therefore go unnoticed on the code side. The only possible
# check is in the database:
#
#   docker exec iris-db psql -U postgres -d iris_db \
#     -c "select case_id, severity_id from cases order by case_id desc limit 5"
FIELD_SEVERITY = "severity_id"

# Mapping effective severity (Wazuh scale 1-15, cf. assets.severity) -> IRIS
# name. Lower bounds inclusive, read from top to bottom.
#
# We start from the EFFECTIVE severity and not from `max_level` alone: it is
# already "how hard it fires" x "on what", and the project only needs one
# definition of gravity. The analyst therefore finds in the IRIS queue the exact
# order the pipeline applied, and the value shown in the case description
# ("effective severity 14/15") explains the colour they see.
THRESHOLDS_SEVERITY = (
    (15, SEV_CRITICAL),   # proven attack on an asset that matters
    (12, SEV_HIGH),       # incident-opening level of the pipeline
    (8, SEV_MEDIUM),
    (4, SEV_LOW),
    (0, SEV_INFO),
)


def severity_name(severity: int, ueba: bool = False, verdict: str = "",
                 actions=()) -> str:
    """IRIS severity name for an incident. Pure function.

    Three rules, in this order:

    1. the `THRESHOLDS_SEVERITY` scale applied to the effective severity;
    2. **UEBA floor at Medium**: an incident born from the behavioural engine has
       a low `max_level` BY CONSTRUCTION (it comes from level 3-11 alerts, cf.
       ueba.py). The scale would file it as "Low" when it only exists because a
       statistical deviation justified it — that is, the opposite of what the
       colour would tell the analyst;
    3. **false-positive ceiling at Low**: a case documenting legitimate activity
       must not sit at the top of the queue. UNLESS the deterministic guardrail
       refused the closure (`escalate_human` in the final actions): the model's
       verdict is then precisely what we do not believe, and downgrading the
       severity would amount to applying anyway the decision we just refused —
       exactly what an injection is after.
    """
    name = SEV_INFO
    for floor, label in THRESHOLDS_SEVERITY:
        if severity >= floor:
            name = label
            break

    order = [SEV_INFO, SEV_LOW, SEV_MEDIUM, SEV_HIGH, SEV_CRITICAL]
    if ueba and order.index(name) < order.index(SEV_MEDIUM):
        name = SEV_MEDIUM
    if (verdict == "false_positive" and "escalate_human" not in (actions or [])
            and order.index(name) > order.index(SEV_LOW)):
        name = SEV_LOW
    return name


# Name -> id mapping, read once per process from the IRIS server.
_SEVERITIES_ID: dict[str, int] | None = None

# Fallback if `/manage/severities/list` is unreachable: the ids observed on IRIS
# 2.4. The fallback is explicitly DECLARED possibly-wrong — an approximate
# severity beats a case with no severity, but we log it.
_SEVERITIES_FALLBACK = {"informational": 3, "low": 4, "medium": 1, "high": 5,
                    "critical": 6}


def _severity_id(case, name: str) -> int | None:
    global _SEVERITIES_ID
    if _SEVERITIES_ID is None:
        try:
            items = case._s.pi_get("/manage/severities/list").get_data()
            _SEVERITIES_ID = {str(s["severity_name"]).lower(): s["severity_id"]
                             for s in items}
        except Exception as e:  # noqa: BLE001
            log.warning("IRIS severity list unreadable (%s): falling back on "
                        "the default ids", e)
            _SEVERITIES_ID = dict(_SEVERITIES_FALLBACK)
    return _SEVERITIES_ID.get(name.lower())


def _set_severity(case, case_id: int, incident: dict, triage: dict) -> str | None:
    """Set the severity of the case. Best-effort: never blocking.

    `add_case` takes no severity (every case is born "Low") and neither does the
    client's `update_case`: we go through the raw endpoint.
    """
    severity = incident.get("severity") or incident.get("max_level") or 0
    name = severity_name(severity, bool(incident.get("ueba")),
                       triage.get("verdict") or "", triage.get("actions") or [])
    sid = _severity_id(case, name)
    if sid is None:
        log.warning("severity \"%s\" unknown to the IRIS server: case #%s left "
                    "as is", name, case_id)
        return None
    try:
        r = case._s.pi_post(f"/manage/cases/update/{case_id}",
                            data={FIELD_SEVERITY: sid})
        if not r.is_success():
            log.warning("severity not set on case #%s: %s", case_id,
                        r.get_msg())
            return None
    except Exception as e:  # noqa: BLE001
        log.warning("severity not set on case #%s: %s", case_id, e)
        return None
    return name


def _description(incident: dict, verdict: str, update: bool = False) -> str:
    """Description of the case. ONE single form, at creation and at refresh.

    The refresh used to rewrite a description without the asset priority: a case
    ten minutes old lost the context that justified its place in the queue.
    """
    desc = (f"Incident #{incident['id']} corrélé par le soc-agent, "
            f"{incident['alert_count']} alertes, niveau max "
            f"{incident['max_level']}/15")
    if incident.get("priority"):
        role = incident.get("asset_role") or "rôle non déclaré"
        desc += (f", asset P{incident['priority']} ({role}), sévérité effective "
                 f"{incident.get('severity') or incident['max_level']}/15")
    desc += f". Verdict IA : {verdict}."
    if update:
        desc += " (mis à jour — nouvelles alertes rattachées)"
    return desc


