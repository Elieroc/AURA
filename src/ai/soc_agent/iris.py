def _remediation_allowed(incident: dict) -> bool:
    """Can the autonomous remediation fire on this incident?

    Deterministic barrier, decided outside the model. The pipeline acts without
    human validation because it starts from a seed of level >= 12: a Wazuh rule
    that already required several correlations. A UEBA incident, on the other
    hand, starts from a STATISTICAL score whose accuracy is not measured yet —
    letting it isolate a host would mean handing production over to an
    uncalibrated threshold. The LLM verdict is rendered, the case is created, the
    proposed actions are written in the report; nothing is executed while
    UEBA_MITIGATE is false.

    This is NOT a disguised human gate: it is the same reasoning as `evaluate.py`
    ("we do not act on what we have not measured"), applied to a new engine. The
    flag goes up once the UEBA verdicts have been labelled.
    """
    if incident.get("ueba") and not config.UEBA_MITIGATE:
        log.info("#%s: autonomous remediation NOT executed — incident of UEBA "
                 "origin (score %s) and UEBA_MITIGATE=false. The case carries "
                 "the proposed actions, the analyst decides.",
                 incident.get("id"), incident.get("ueba_score"))
        return False
    return True


def create_case(conn, incident: dict, triage: dict) -> int:
    # Idempotence guardrail: if this incident duplicates a sibling already
    # pushed to IRIS (a miss of the attach-to-existing pass), we reuse its case
    # instead of opening a second one. The duplicate incident is merged into the
    # sibling.
    adopted = _merge_if_duplicate(conn, incident)
    if adopted is None:
        # Approach A: failing a duplicate on the same host, attachment to an
        # already open campaign (other hosts included) on an attacker marker.
        adopted = _merge_campaign(conn, incident)
    if adopted is not None:
        log.info("incident #%s -> merged into IRIS case #%s (no new case)",
                 incident["id"], adopted)
        return adopted

    alerts = _alerts(conn, incident["id"])
    verdict = triage["verdict"]
    fp = verdict == "false_positive"

    log.debug("incident #%s: IRIS case creation (verdict=%s, alerts=%d)",
              incident["id"], verdict, incident["alert_count"])
    try:
        case = _client()
        log.debug("  IRIS client obtained (url=%s)", config.IRIS_URL)
    except Exception as e:
        log.error("  IRIS client failed: %s", e)
        raise RuntimeError(f"IRIS client failed: {e}") from e

    name = _name_case(conn, incident, triage, alerts)
    # Asset priority in the DESCRIPTION and in a TAG (filterable in IRIS). The
    # SEVERITY of the case is set after creation: `add_case` does not take it and
    # every case is born "Low".
    priority = incident.get("priority")
    desc = _description(incident, verdict)

    log.debug("  add_case call (name=%s, cust=%s)", name[:50],
              config.IRIS_CUSTOMER)
    r = case.add_case(
        case_name=name,
        case_description=desc,
        case_customer=config.IRIS_CUSTOMER,
        case_classification=_classification(incident, alerts),
        soc_id=f"Aura-SOC-{incident['id']}",
    )
    log.debug("  add_case answer: success=%s", r.is_success())
    if not r.is_success():
        log.error("  IRIS error msg: %s", r.get_msg())
        raise RuntimeError(f"case creation failed: {r.get_msg()}")
    case_id = r.get_data()["case_id"]

    # Case attached BEFORE the remediation: mitigate.run opens its own
    # connection and reads iris_case_id to drop its notes there. Immediate commit
    # so that it sees it. needs_refresh set back to false: the case reflects the
    # incident in its current state.
    conn.execute(
        "UPDATE incidents SET iris_case_id = %s, status = %s, "
        "needs_refresh = false WHERE id = %s",
        (case_id, "fp_classified" if fp else "case_open", incident["id"]))
    conn.commit()

    # Tags = hostname of the affected machine + asset priority (add_case does
    # not take tags, hence the update right after the creation).
    _tag(case, case_id, incident.get("agent_name"),
            f"P{priority}" if priority else None)
    sev = _set_severity(case, case_id, incident, triage)
    if sev:
        log.info("case #%s: IRIS severity %s (effective %s/15, asset P%s)",
                 case_id, sev, incident.get("severity"), priority)

    # IOCs (best-effort: an unknown type must not fail the case) and the
    # "affected machine" asset. The ids collected are used to link the timeline:
    # without those links, the IRIS Graph tab stays empty.
    ioc_ids = _set_iocs(case, case_id, alerts)
    asset_ids = _set_asset_machine(case, case_id, incident, alerts,
                                     compromised=not fp)

    # WHITELIST task on "On hold": the analyst fills it in and moves it to
    # 'To do' when they want an exception; soc_agent.whitelist_task then
    # processes it cyclically. Best-effort: a failure does not block the
    # creation of the case.
    _set_whitelist_task(case, case_id)

    # AUTOMATIC remediation, before the report: the actions decided at triage
    # are executed now (isolation, blocking, account disabling), traced in the
    # `mitigations` table + dedicated IRIS tasks. The report then recaps them.
    # Barriers kept inside mitigate.run (dry-run if MITIGATE_EXECUTE=false,
    # suspension on injection patterns).
    # Deferred import: mitigate imports iris, we break the cycle at call time.
    if not fp and _remediation_allowed(incident):
        try:
            from . import mitigate
            mitigate.run(incident["id"])
        except Exception as e:  # noqa: BLE001 — a failed remediation does not
            # block the creation of the case; it is traced as 'failed'.
            log.warning("auto remediation #%s: %s", incident["id"], e)

    # True positive: the UEBA traits involved must never become a habit again.
    # Without this, a patient attacker normalises their own tooling by running it
    # every day until it stops being scored.
    #
    # NEVER on an incident of UEBA origin, though: the freeze would be circular.
    # The behavioural score designates the incident, the LLM declares it a true
    # positive, and the freeze re-injects the traits that produced the score by
    # pushing them to the ceiling — permanently, since `purge()` explicitly
    # preserves `seen_in_tp`. Same reasoning as `UEBA_MITIGATE`: a verdict
    # rendered on an uncalibrated score does not rewrite the baseline that
    # produced it.
    #
    # Observed in production on 2026-08-08: incident #2550 (case #193) froze 24
    # traits, among them `compte=WIN-DC$` (38,650 observations),
    # `heure=hors_ouvre` (27,954) and `rule_id=60137` (19,471) — the most banal
    # traits of the estate, stuck at 12 bits. The following signals climbed to
    # 238 without anything happening, and the daily budget went into that noise.
    if not fp and not incident.get("ueba"):
        try:
            from . import ueba
            n = ueba.mark_tp(incident["id"])
            if n:
                log.info("#%s: %d UEBA trait(s) frozen (seen in a true "
                         "positive)", incident["id"], n)
        except Exception as e:  # noqa: BLE001
            log.warning("UEBA TP marking #%s: %s", incident["id"], e)

    # Analysis note, in a dedicated directory. After the remediation: the recap
    # of the executed actions depends on it.
    content = (_note_fp(triage, _rule_whitelist(conn, alerts)) if fp
               else _note_tp(conn, incident, triage, alerts,
                             _iocs_of_case(case, case_id, alerts)))
    title = "Analyse — Faux positif" if fp else "Rapport d'analyse"
    _set_note(case, case_id, title, content)

    # Vulnerability exposure of the affected machine. Laid on FALSE POSITIVES
    # too: the verdict is about the event, not about the state of the host, and a
    # machine past its patching deadline stays so whether the alert of the day
    # was founded or not.
    _set_exposure(case, case_id, conn, incident, alerts)

    # Timeline: the kill chain, one event per rule (TP only — an FP has no
    # attack chronology to rebuild).
    # Re-read AFTER the remediation: mitigate laid the targeted accounts there as
    # assets, which we want to see appear in the graph.
    if not fp:
        _timeline(case, case_id, alerts, incident["agent_id"],
                  asset_ids, ioc_ids, _assets_case(case, case_id))
        # Evidence tab: every raw alert archived (real log + deep link).
        _evidences(conn, case, case_id, incident["id"], alerts,
                   incident["agent_id"])

    conn.commit()
    return case_id


def _verdict_changed(conn, incident_id: int) -> bool:
    """Did the verdict or the actions change at the last triage?

    Fix #1 (token explosion of 2026-07-30): on a refresh where the replayed
    triage returns the SAME verdict and the SAME actions as the previous one, the
    LLM report would come out word for word (reproducible verdict, temp 0.2 +
    seed). We then avoid regenerating the `report` call — the most expensive of
    the pipeline (~2000 completion tokens). Returns True (so "regenerate") if
    there is only one triage: that is the first analysis."""
    rows = conn.execute(
        "SELECT verdict, actions FROM triages WHERE incident_id = %s "
        "ORDER BY created_at DESC LIMIT 2", (incident_id,)).fetchall()
    if len(rows) < 2:
        return True
    return (rows[0]["verdict"] != rows[1]["verdict"]
            or list(rows[0]["actions"]) != list(rows[1]["actions"]))


def refresh_case(conn, incident: dict, triage: dict) -> int:
    """Update the existing case of an incident enriched with new alerts.

    This is the other half of the anti-duplicate fix: when a burst of an ongoing
    intrusion is attached to an incident that ALREADY has a case (cf. the
    attach-to-existing pass of correlate + needs_refresh), we complete that case
    instead of opening a second one. Missing IOCs added, timeline rebuilt,
    analysis note and description brought up to date, hostname tag reasserted.
    """
    case_id = incident["iris_case_id"]
    case = _client()

    # Case deleted on the IRIS side: the link in the database dangles. We set it
    # back to NULL and recreate, rather than writing forever into a case_id that
    # no longer exists.
    #
    # The symptom is misleading: IRIS does not answer 404 but **500**. Its access
    # control, not finding the case among the user's, falls back on "am I a
    # server administrator?", which reads `session['permissions']` — absent under
    # API-key authentication (KeyError, cf. iris_engine/access_control/utils.py).
    # A deleted case and a genuine permission problem therefore produce the same
    # unreadable error.
    if not _case_exists(case, case_id):
        log.warning("IRIS case #%s not found (deleted?) — incident #%s "
                    "recreated", case_id, incident["id"])
        conn.execute("UPDATE incidents SET iris_case_id = NULL WHERE id = %s",
                     (incident["id"],))
        conn.commit()
        return create_case(conn, dict(incident, iris_case_id=None), triage)

    alerts = _alerts(conn, incident["id"])
    fp = triage["verdict"] == "false_positive"
    desc = _description(incident, triage["verdict"], update=True)
    try:
        case.update_case(case_id=case_id, case_description=desc)
    except Exception as e:  # noqa: BLE001
        log.debug("case description update #%s: %s", case_id, e)

    _tag(case, case_id, incident.get("agent_name"),
            f"P{incident['priority']}" if incident.get("priority") else None)
    # The severity is REPLAYED: a burst may have raised the max level, hence the
    # effective severity. A case opened as "High" that becomes a proven attack
    # must change colour in the queue, otherwise the analyst sorts on stale
    # information.
    _set_severity(case, case_id, incident, triage)
    ioc_ids = _set_iocs(case, case_id, alerts)
    asset_ids = _set_asset_machine(case, case_id, incident, alerts,
                                     compromised=not fp)

    # Remediation replayed: idempotent (unique key incident/action/target), it
    # only covers any new targets that appeared with the burst.
    if not fp and _remediation_allowed(incident):
        try:
            from . import mitigate
            mitigate.run(incident["id"])
        except Exception as e:  # noqa: BLE001
            log.warning("refresh remediation #%s: %s", incident["id"], e)

    # Analysis note. The FP one is cheap (no LLM call) -> always regenerated.
    # The TP report calls the LLM: fix #1, we only regenerate it if the verdict or
    # the actions changed since the note in place (otherwise identical).
    if fp:
        _set_note(case, case_id, "Analyse — Faux positif",
                    _note_fp(triage, _rule_whitelist(conn, alerts)))
    elif _verdict_changed(conn, incident["id"]):
        _set_note(case, case_id, "Rapport d'analyse",
                    _note_tp(conn, incident, triage, alerts,
                             _iocs_of_case(case, case_id, alerts)))
    else:
        log.info("#%s report not regenerated: verdict unchanged since the note "
                 "in place (saves the LLM report call)", incident["id"])

    # This one is always regenerated: it costs no call to the model, and the
    # exposure of the machine moves independently of the verdict (a patch applied
    # between two bursts must show in the case).
    _set_exposure(case, case_id, conn, incident, alerts)

    if not fp:
        _rebuild_timeline(case, case_id, alerts, incident["agent_id"],
                               asset_ids, ioc_ids, _assets_case(case, case_id))
        # Evidence: insertion only of the newly attached alerts (idempotent).
        _evidences(conn, case, case_id, incident["id"], alerts,
                   incident["agent_id"])

    conn.execute(
        "UPDATE incidents SET needs_refresh = false, status = %s WHERE id = %s",
        ("fp_classified" if fp else "case_open", incident["id"]))
    conn.commit()
    return case_id


# Two populations: the incidents WITHOUT a case (to create) and those that have
# a case but gained alerts since (needs_refresh -> to update, not to duplicate).
# Same row shape for both, we add iris_case_id.
_SELECT_BASE = """
SELECT DISTINCT ON (i.id)
       i.id, i.agent_id, i.agent_name, i.first_seen, i.last_seen,
       i.alert_count, i.max_level, i.mitre_tactics, i.entities, i.iris_case_id,
       i.ueba, i.ueba_score, i.ueba_patterns, i.priority, i.severity,
       i.asset_role,
       t.verdict, t.confidence, t.mitre, t.actions, t.reason
  FROM incidents i
  JOIN triages t ON t.incident_id = i.id
 WHERE {filter}
   AND (%(only_one)s::bigint IS NULL OR i.id = %(only_one)s)
 ORDER BY i.id, t.created_at DESC
"""
SELECT_TO_PROCESS = _SELECT_BASE.format(
    filter="i.iris_case_id IS NULL AND i.status <> 'fp_ueba'")
SELECT_TO_REFRESH = _SELECT_BASE.format(
    filter="i.iris_case_id IS NOT NULL AND i.needs_refresh")


def create_cases(only_one: int | None = None) -> list[tuple[int, int, str]]:
    """Create the missing cases AND update those of the enriched incidents.

    Returns (incident_id, case_id, verdict). An incident already pushed to IRIS
    that gained alerts (needs_refresh) has its case COMPLETED, never duplicated.
    """
    done: list[tuple[int, int, str]] = []
    with psycopg.connect(config.PG_DSN, row_factory=dict_row) as conn:
        to_create = conn.execute(SELECT_TO_PROCESS, {"only_one": only_one}).fetchall()
        for inc in to_create:
            # Incident of UEBA origin judged a false positive: NO case.
            #
            # An FP case makes sense for an incident of level >= 12: a rule fired
            # hard, the analyst wants to see why it was nothing. A UEBA incident,
            # on the other hand, rests only on an uncalibrated behavioural score
            # (which is also why UEBA_MITIGATE is false): when the LLM says
            # "false positive", there is nothing to document, and the case is
            # pure noise in the analyst's queue. The verdict stays in the
            # database (`triages` table) for the whitelist and the metrics.
            #
            # Origin: IRIS case #192, opened on 2 level-3 alerts (scheduling of
            # the Windows Software Protection service).
            if inc["ueba"] and inc["verdict"] == "false_positive":
                conn.execute(
                    "UPDATE incidents SET status = %s, needs_refresh = false "
                    "WHERE id = %s", ("fp_ueba", inc["id"]))
                conn.commit()
                log.info("incident #%s (UEBA, score %s) judged a false "
                         "positive: no IRIS case opened", inc["id"],
                         inc["ueba_score"])
                continue
            triage = {k: inc[k] for k in
                      ("verdict", "confidence", "mitre", "actions", "reason")}
            try:
                case_id = create_case(conn, inc, triage)
                done.append((inc["id"], case_id, inc["verdict"]))
                print(f"  incident #{inc['id']} -> case IRIS #{case_id} "
                      f"({inc['verdict']})")
            except Exception as e:  # noqa: BLE001
                log.error("case creation failed for incident #%s: %s",
                          inc["id"], e)
                # Rollback first: if the failure comes from an SQL error, the
                # transaction is aborted and the UPDATE that follows would fail
                # in turn — the incident would not even be marked for a retry,
                # and the whole rest of the batch would fall with it.
                conn.rollback()
                # mark incident so we retry next cycle
                conn.execute("UPDATE incidents SET status = %s WHERE id = %s",
                           ("case_creation_failed", inc["id"]))
                conn.commit()

        to_refresh = conn.execute(
            SELECT_TO_REFRESH, {"only_one": only_one}).fetchall()
        for inc in to_refresh:
            triage = {k: inc[k] for k in
                      ("verdict", "confidence", "mitre", "actions", "reason")}
            try:
                case_id = refresh_case(conn, inc, triage)
                done.append((inc["id"], case_id, inc["verdict"]))
                print(f"  incident #{inc['id']} -> case IRIS #{case_id} MAJ "
                      f"({inc['verdict']}, {inc['alert_count']} alertes)")
            except Exception as e:  # noqa: BLE001
                log.error("case refresh failed for incident #%s: %s",
                          inc["id"], e)
                # Without this rollback, an SQL error leaves the transaction
                # aborted and ALL the following incidents die in cascade on
                # "current transaction is aborted" — a single broken incident
                # took the whole batch with it. Lived on 2026-08-14: eleven
                # refreshes lost for a single faulty query.
                conn.rollback()
    return done


def clean_iocs(simulation: bool = True) -> list[tuple[int, str, str]]:
    """Remove from the existing cases the IOCs that became redundant.

    `_set_iocs` only ADDS what is missing, it never removes: the cases created
    before the "one file = one IOC" fold keep their three lines per file (path,
    sha256, md5). This cleanup brings them back to one.

    Caution: we only delete values that this code itself produced earlier for a
    file now represented by its hash — never an IOC added by hand by an analyst,
    which cannot appear in that list.
    """
    to_do: list[tuple[int, str, str]] = []
    case = _client()
    with psycopg.connect(config.PG_DSN, row_factory=dict_row) as conn:
        incidents = conn.execute(
            "SELECT id, iris_case_id FROM incidents "
            "WHERE iris_case_id IS NOT NULL ORDER BY id").fetchall()
        for inc in incidents:
            alerts = conn.execute(
                "SELECT * FROM alerts WHERE incident_id = %s ORDER BY ts",
                (inc["id"],)).fetchall()
            if not alerts:
                continue
            # What the code produces TODAY: the reference list.
            guards = {v for v, _t, _d in _iocs(alerts)}
            # The file values known from those alerts: paths and hashes.
            # Anything in there but no longer in `guards` is a leftover of the
            # old form, folded since into a description.
            known = _values_file(alerts)
            if not _case_exists(case, inc["iris_case_id"]):
                print(f"  case #{inc['iris_case_id']}: not found in IRIS "
                      f"(deleted) — incident #{inc['id']} skipped, it will be "
                      "recreated at the next refresh")
                continue
            try:
                presents = (case.list_iocs(inc["iris_case_id"]).get_data()
                            or {}).get("ioc") or []
            except Exception as e:                            # noqa: BLE001
                log.warning("case #%s: unreadable IOCs (%s)",
                            inc["iris_case_id"], e)
                continue
            for i in presents:
                value = i.get("ioc_value")
                if not value or value in guards or value not in known:
                    continue
                to_do.append((inc["iris_case_id"], value, i.get("ioc_id")))
                if not simulation:
                    try:
                        case.delete_ioc(i["ioc_id"], cid=inc["iris_case_id"])
                    except Exception as e:                    # noqa: BLE001
                        log.warning("IOC deletion %s: %s", value, e)
    return to_do


def _values_file(alerts: list[dict]) -> set[str]:
    """File paths and hashes present in those alerts.

    Perimeter of the cleanup: we delete nothing that does not come from there.
    """
    values: set[str] = set()
    for a in alerts:
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        data = raw.get("data", {}) or {}
        yara = data.get("yara") or {}
        vt = (data.get("virustotal", {}) or {}).get("source", {}) or {}
        sc = raw.get("syscheck", {}) or {}
        for v in (data.get("file_path"), yara.get("scan_path"),
                  _path_target(data.get("file_path") or yara.get("scan_path")),
                  data.get("sha256"), data.get("sha1"), data.get("md5"),
                  vt.get("file"), vt.get("sha256"), vt.get("sha1"), vt.get("md5"),
                  sc.get("path"), sc.get("sha256_after"), sc.get("sha1_after"),
                  sc.get("md5_after")):
            if v:
                values.add(str(v))
    return values


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--incident", type=int, default=None)
    ap.add_argument("--clean-iocs", action="store_true",
                    help="remove the redundant IOCs from the existing cases "
                         "(one file = one IOC, hash preferred over path)")
    ap.add_argument("--apply", action="store_true",
                    help="with --clean-iocs: really delete (without this flag, "
                         "simulation)")
    args = ap.parse_args()

    if args.clean_iocs:
        done = clean_iocs(simulation=not args.apply)
        verb = "deleted" if args.apply else "to delete"
        for case_id, value, _ in done:
            print(f"  case #{case_id}: {verb} {value}")
        print(f"  {len(done)} redundant IOC(s) {verb}.")
        if done and not args.apply:
            print("  Run again with --apply to delete.")
        return

    created = create_cases(args.incident)
    if not created:
        print("No incident to push to IRIS.")


if __name__ == "__main__":
    main()
