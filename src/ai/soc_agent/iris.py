def _tag(case, case_id: int, agent_name: str | None,
            *extras: str | None) -> None:
    """Add the hostname of the affected machine to the case tags (union).

    An analyst can then find every case of a given machine by the tag. Union with
    the existing ones: we do not overwrite tags set by hand. add_case does not
    accept tags — hence the update_case right after creation.

    `extras`: extra tags (asset priority, "P1"...), ignored when empty.
    """
    new = {t for t in (agent_name, *extras) if t}
    if not new:
        return
    tags: set[str] = set()
    try:
        gc = case.get_case(case_id)
        if gc.is_success():
            raw = gc.get_data().get("case_tags") or ""
            tags = {t.strip() for t in raw.split(",") if t.strip()}
    except Exception as e:  # noqa: BLE001 — the tag never blocks the case
        log.debug("reading tags of case #%s: %s", case_id, e)
    if new <= tags:
        return
    tags |= new
    try:
        case.update_case(case_id=case_id, case_tags=sorted(tags))
    except Exception as e:  # noqa: BLE001
        log.debug("tagging case #%s: %s", case_id, e)


def _case_exists(case, case_id: int | None) -> bool:
    """Is the case still there? False if it was deleted in IRIS.

    No exception escapes: this test is there to DECIDE what to do next, it must
    not itself become a cause of failure.
    """
    if not case_id:
        return False
    try:
        return bool(case.get_case(case_id).is_success())
    except Exception as e:  # noqa: BLE001
        log.debug("existence of case #%s undeterminable: %s", case_id, e)
        return False


def _set_iocs(case, case_id: int, alerts: list[dict]) -> dict[str, int]:
    """Update the case: add the missing IOCs, refresh the descriptions.

    Returns the value -> ioc_id table of ALL the IOCs of the case (existing ones
    included): the timeline uses it to attach every event to its indicators,
    which is the condition for the IRIS Graph tab to have something to draw (it
    only reads `case_events_ioc`).

    The description is rewritten when it changed. Without that, a case never
    converges towards what the code produces: when the "one file = one IOC" fold
    was introduced, the hashes already present kept their old description and the
    file path — now carried by that description — stayed unfindable in the case.
    """
    ids: dict[str, int] = {}
    descriptions: dict[str, str] = {}
    try:
        d = case.list_iocs(case_id).get_data() or {}
        for i in d.get("ioc") or []:
            if i.get("ioc_value") and i.get("ioc_id"):
                ids[i["ioc_value"]] = i["ioc_id"]
                descriptions[i["ioc_value"]] = i.get("ioc_description") or ""
    except Exception as e:  # noqa: BLE001
        log.debug("IOC list of case #%s: %s", case_id, e)
    for value, type_ioc, description in _iocs(alerts):
        if value in ids:
            # Only if it changed: one useless write per IOC per refresh, on
            # every case, would load IRIS for nothing.
            if descriptions.get(value) != description:
                try:
                    case.update_ioc(ids[value], description=description,
                                    cid=case_id)
                except Exception as e:  # noqa: BLE001
                    log.debug("IOC description update %s: %s", value, e)
            continue
        try:
            r = case.add_ioc(value=value, ioc_type=type_ioc,
                             description=description, cid=case_id)
            if r.is_success():
                ids[value] = (r.get_data() or {}).get("ioc_id")
        except Exception as e:  # noqa: BLE001
            log.debug("IOC skipped (%s/%s): %s", type_ioc, value, e)
    return {v: i for v, i in ids.items() if i}


def _type_asset(alerts: list[dict]) -> str:
    """IRIS asset type of the affected machine, deduced from the alerts."""
    for a in alerts:
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        groups = (raw.get("rule", {}) or {}).get("groups") or []
        if any("windows" in str(g).lower() for g in groups) or \
                "win" in (raw.get("data", {}) or {}):
            return "Windows - Computer"
    return "Linux - Server"


def _assets_case(case, case_id: int) -> dict[str, int]:
    """name -> asset_id table of the case assets (including mitigate's)."""
    out: dict[str, int] = {}
    try:
        d = case.list_assets(cid=case_id).get_data() or {}
        items = d.get("assets") if isinstance(d, dict) else d
        for a in items or []:
            if a.get("asset_name") and a.get("asset_id"):
                out[a["asset_name"]] = a["asset_id"]
    except Exception as e:  # noqa: BLE001
        log.debug("asset list of case #%s: %s", case_id, e)
    return out


def _set_asset_machine(case, case_id: int, incident: dict,
                         alerts: list[dict], compromised: bool) -> list[int]:
    """Create (or find) the "affected machine" asset of the case.

    This is the pivot node of the graph: every timeline event is attached to it,
    and the event's IOCs hang off it in a star. Without at least one asset linked
    to an event, the Graph tab stays empty even with IOCs.
    """
    name = incident.get("agent_name") or str(incident["agent_id"])
    existing = _assets_case(case, case_id)
    if name in existing:
        return [existing[name]]

    ip = None
    for a in alerts:
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        ip = (raw.get("agent", {}) or {}).get("ip")
        if ip:
            break
    try:
        r = case.add_asset(
            name=name,
            asset_type=_type_asset(alerts),
            analysis_status="Started",
            # 1 = compromised, 0 = to be determined. Hard-coded rather than by
            # name: the graph tests `asset_compromise_status_id == 1` to pick the
            # icon, and it saves one lookup round-trip per case.
            compromise_status=1 if compromised else 0,
            description=(f"Endpoint Wazuh {incident['agent_id']} — "
                         f"{incident['alert_count']} alertes corrélées, "
                         f"niveau max {incident['max_level']}/15."),
            ip=ip,
            cid=case_id)
        if r.is_success():
            return [(r.get_data() or {})["asset_id"]]
        log.debug("machine asset not created (case #%s): %s", case_id,
                  r.get_msg())
    except Exception as e:  # noqa: BLE001 — the asset never blocks the case
        log.debug("machine asset of case #%s: %s", case_id, e)
    return []


# Mark of a report written without an LLM analysis (fallback on the triage
# reason). Also acts as a guard: a degraded report never overwrites a complete
# one.
MARK_DEGRADED = "⚠️ **Rapport dégradé"


def _note_is_degraded(case, case_id: int, note_id: int) -> bool:
    """True if the existing note is already a fallback (or unreadable)."""
    try:
        d = case.get_note(note_id, cid=case_id).get_data() or {}
        return MARK_DEGRADED in (d.get("note_content") or "")
    except Exception as e:  # noqa: BLE001 — when in doubt, do not overwrite
        log.debug("reading note %s: %s", note_id, e)
        return False


def _set_note(case, case_id: int, title: str, content: str,
                directory: str = DIR_ANALYSIS) -> None:
    """Create or UPDATE a note in the requested directory.

    When a case is refreshed, we replace the content of the existing note rather
    than stack a second one: the case stays readable.

    ONE exception: a DEGRADED report (failed LLM analysis, fallback on the triage
    reason) never overwrites a complete report. An incident is re-triaged on
    every new alert, so the report is rewritten in a loop; on 2026-08-02 the full
    report of cases 90 and 91 was replaced by the two-line fallback because the
    last call had exhausted its token budget. Losing a successful analysis
    because of a later failure is a pure regression, never a refresh.
    """
    dir_id = None
    note_id = None
    try:
        for d in case.list_notes_directories(cid=case_id).get_data() or []:
            if d.get("name") == directory:
                dir_id = d["id"]
                for n in d.get("notes") or []:
                    if n.get("title") == title:
                        note_id = n["id"]
                        break
                break
    except Exception as e:  # noqa: BLE001
        log.debug("note list of case #%s: %s", case_id, e)
    if note_id is not None:
        if (MARK_DEGRADED in content
                and not _note_is_degraded(case, case_id, note_id)):
            log.warning("case #%s: degraded report NOT written, the existing "
                        "note is a complete analysis", case_id)
            return
        try:
            case.update_note(note_id=note_id, note_content=content, cid=case_id)
            return
        except Exception as e:  # noqa: BLE001
            log.debug("note update %s: %s", note_id, e)
    if dir_id is None:
        rd = case.add_notes_directory(directory_name=directory, cid=case_id)
        dir_id = rd.get_data()["id"] if rd.is_success() else None
    case.add_note(note_title=title, note_content=content,
                  directory_id=dir_id, cid=case_id)


def _is_auto_legacy(case, case_id: int, ev: dict) -> bool:
    """Event laid down by an earlier version of the soc-agent (no tag).

    Catch-up: those events only carry `event_source = "Wazuh"`, which is absent
    from the timeline listing — the event has to be re-read to decide. One call
    per untagged event, which disappears after the first cleanup.
    """
    try:
        d = case.get_event(ev["event_id"], cid=case_id).get_data() or {}
        return (d.get("event_source") or "") == "Wazuh"
    except Exception as e:  # noqa: BLE001
        log.debug("reading event %s: %s", ev.get("event_id"), e)
        return False


def _rebuild_timeline(case, case_id: int, alerts: list[dict],
                           agent_id: str, asset_ids: list[int] | None = None,
                           ioc_ids: dict[str, int] | None = None,
                           assets_name: dict[str, int] | None = None) -> None:
    """Erase the auto events (tag `soc-agent`) and rebuild them.

    An attached burst lengthens a rule group or creates one; re-posting
    everything as is would duplicate. So we delete the events laid down by the
    soc-agent, never those entered by an analyst, then recreate them from the
    current state.

    The marker is the **tag** `soc-agent`, not `event_source`: the IRIS timeline
    listing does not return that field, so filtering on it never deleted anything
    and stacked duplicates on every refresh.
    """
    try:
        tl = case.list_events(cid=case_id).get_data().get("timeline") or []
    except Exception as e:  # noqa: BLE001
        log.debug("timeline list of case #%s: %s", case_id, e)
        tl = []
    for ev in tl:
        tags = {t.strip() for t in (ev.get("event_tags") or "").split(",")}
        if TAG_AUTO not in tags and not _is_auto_legacy(case, case_id, ev):
            continue
        try:
            case.delete_event(ev["event_id"], cid=case_id)
        except Exception as e:  # noqa: BLE001
            log.debug("deleting event %s: %s", ev.get("event_id"), e)
    _timeline(case, case_id, alerts, agent_id, asset_ids, ioc_ids, assets_name)


def _classification(incident: dict, alerts: list[dict]) -> int:
    groups = {g for a in alerts for g in (a.get("rule_groups") or [])}
    tactics = set(incident.get("mitre_tactics") or [])
    if "ransomware" in groups or "Impact" in tactics:
        return CLASSIF_RANSOMWARE
    if {"authentication_failed", "authentication_failures"} & groups:
        return CLASSIF_RAW
    return CLASSIF_DEFAULT


# Directories where a file signals malicious activity. Elsewhere (/usr, /bin,
# /etc...), a path is a legitimate binary or config that the attacker only
# *used* — not an IOC. /etc/passwd is not an indicator; /dev/shm/.kworker is.
_DIRS_SUSPICIOUS = ("/tmp/", "/var/tmp/", "/dev/shm/", "/run/shm/",
                  "/root/.ssh", "/var/www/", "/usr/lib/cgi-bin/")
# System accounts: their presence in a log is not an IOC.
_ACCOUNTS_SYSTEM = {"root", "www-data", "daemon", "nobody", "sync", "sys", "bin"}
# Target of a reverse shell in a /dev/tcp|udp/<ip>/<port> redirection.
_RE_REVSHELL = re.compile(r"/dev/(?:tcp|udp)/(\d{1,3}(?:\.\d{1,3}){3})/(\d{1,5})")
# auditd proctitle: the full command line, hex-encoded.
_RE_PROCTITLE = re.compile(r"proctitle=([0-9A-Fa-f]{8,})")
# Account creation in a command (last token = account name).
_RE_USERADD = re.compile(r"\b(?:useradd|adduser)\b.*?([A-Za-z_][\w-]*)\s*$")
# Windows account creation on the command line: "net user <name> ... /add"
# (with or without /domain). Catches the AD backdoor when only net.exe is seen.
_RE_NETUSER_ADD = re.compile(r"\bnet\d?\s+user\s+([^\s/]+).*?/add", re.IGNORECASE)
# Prefix of the YARA scanner sshfs mount: /mnt/yaritrust/<host>_<ip>/...
_RE_MOUNT_SCAN = re.compile(r"^/mnt/yaritrust/[^/]+/")
# Absolute path in a command line. We stop at the characters that separate
# shell tokens rather than on a list of allowed characters: an attacker's file
# name can contain just about anything.
_RE_PATH_ARGV = re.compile(r"/[^\s'\"><|;,()]+")
# Paths under /tmp that belong to the system machinery, not to the attacker:
# private mounts of systemd units, X11/ICE sockets.
_RE_ARGV_NOISE = re.compile(
    r"^/tmp/(?:systemd-private-|\.X11-unix|\.ICE-unix|\.font-unix|\.XIM-unix)")

