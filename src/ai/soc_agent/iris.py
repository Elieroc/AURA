def _traits(conn, incident_id: int) -> list[dict]:
    """Kinship/identity fields of an incident (columns, without parsing the raw).

    DISTINCT, and that is what makes the function usable: `_merge_if_duplicate`
    calls it for the current incident AND THEN for every incident candidate to
    the merge, and all its consumers (`_strong_identity`, `_related`,
    `_distinct`) only build SETS — the 100,000th repetition of the same (ip,
    user, tactic) changes no result, it only takes up memory.

    Without the DISTINCT, a flood incident brought back its 126,508 rows, once
    per compared candidate. The cycle was OOM-killed (1 GB limit) on 2026-08-14
    at 11:24, stopping the ingestion: the SOC went blind through the sheer size
    of what it was looking at.
    """
    return conn.execute(
        "SELECT DISTINCT srcip, srcuser, entity, mitre_tactics, rule_groups, "
        "audit_uid FROM alerts WHERE incident_id = %s", (incident_id,)).fetchall()


def _strong_identity(traits: list[dict]) -> tuple[set[str], set[str]]:
    """What NAMES the intrusion: compromised accounts (uid) and IPs.
    Discriminating.

    Root (uid 0) is discarded: a SUID privesc makes it appear everywhere, it does
    not tell two intrusions apart. Two incidents whose strong identities are
    non-empty AND disjoint are DIFFERENT attacks — never to merge (two
    simultaneous chains, uid 1001 vs uid 33/www-data, must stay two cases).
    """
    uids = {str(t["audit_uid"]) for t in traits if t.get("audit_uid") is not None}
    uids -= {"0"}
    ips = {t["srcip"] for t in traits if t.get("srcip")}
    return uids, ips


def _distinct(a: list[dict], b: list[dict]) -> bool:
    ua, ai = _strong_identity(a)
    ub, ib = _strong_identity(b)
    return bool(ua and ub and not (ua & ub)) or bool(ai and ib and not (ai & ib))


def _related(a: list[dict], b: list[dict]) -> bool:
    """Do two incidents share a kinship trait (weak link included)?

    Same criteria as correlate.common_point, applied incident to incident:
    IP/account/concrete object, MITRE tactic or non-generic rule group. The time
    window is already bounded upstream (+/- MAX_INCIDENT_HOURS).
    """
    def feats(al):
        ips = {x["srcip"] for x in al if x.get("srcip")}
        users = {x["srcuser"] for x in al if x.get("srcuser")}
        ents = {x["entity"] for x in al if x.get("entity")
                and not correlate.generic_entity(x["entity"])}
        tacs = {t for x in al for t in (x.get("mitre_tactics") or [])}
        grps = ({g for x in al for g in (x.get("rule_groups") or [])}
                - correlate.GROUPS_GENERIC)
        return ips, users, ents, tacs, grps
    return any(x & y for x, y in zip(feats(a), feats(b)))


def _merge_if_duplicate(conn, incident: dict) -> int | None:
    """Last anti-duplicate guardrail: idempotence at case creation.

    The correlation's attach-to-existing pass normally glues a burst back to its
    incident; if it misses the window because of the cycle batching, two distinct
    incidents describe the SAME intrusion and each would open a case. Here, at
    creation, both incidents and all their alerts are in the database: if a
    sibling incident of the same agent ALREADY has a case, overlaps the window
    (+/- MAX_INCIDENT_HOURS), shares a kinship trait and is not separated by a
    contradictory strong identity, we merge this incident into the sibling and
    reuse its case — never a duplicate. Returns the adopted case_id, or None.
    """
    margin = timedelta(hours=config.MAX_INCIDENT_HOURS)
    siblings = conn.execute(
        "SELECT id, iris_case_id FROM incidents WHERE agent_id = %s "
        "AND id <> %s AND iris_case_id IS NOT NULL "
        "AND last_seen >= %s AND first_seen <= %s ORDER BY id",
        (incident["agent_id"], incident["id"],
         incident["first_seen"] - margin, incident["last_seen"] + margin)).fetchall()
    if not siblings:
        return None

    traits_x = _traits(conn, incident["id"])
    for f in siblings:
        traits_f = _traits(conn, f["id"])
        if _distinct(traits_x, traits_f) or not _related(traits_x, traits_f):
            continue
        return _merge(conn, incident["id"], f["id"], f["iris_case_id"])
    return None


def _merge(conn, src_id: int, dst_id: int, dst_case: int | None) -> int | None:
    """Merge incident src into dst: the alerts of src join dst, the aggregates of
    dst are recomputed, dst is marked for refresh (its case will be completed on
    the next cycle, remediation included), and src is deleted (CASCADE triages /
    mitigations / anon_map; its alerts have already moved). Returns dst_case."""
    conn.execute("UPDATE alerts SET incident_id = %s WHERE incident_id = %s",
                 (dst_id, src_id))
    agg = conn.execute(
        "SELECT count(*) n, min(ts) f, max(ts) l, max(rule_level) lvl, "
        "array_agg(DISTINCT rule_id) r FROM alerts WHERE incident_id = %s",
        (dst_id,)).fetchone()
    conn.execute(
        "UPDATE incidents SET alert_count = %s, first_seen = %s, "
        "last_seen = %s, max_level = %s, rule_ids = %s, needs_refresh = true "
        "WHERE id = %s",
        (agg["n"], agg["f"], agg["l"], agg["lvl"], sorted(agg["r"]), dst_id))
    conn.execute("DELETE FROM incidents WHERE id = %s", (src_id,))
    conn.commit()
    return dst_case


def _signature_campaign(alerts: list[dict]) -> set[str]:
    """Markers BELONGING to the attacker that link the hosts of a single
    campaign: created accounts, external C2 IPs, malicious files/hashes.

    Deliberately NOT the internal IPs (an admin bounce would link the whole
    estate) nor the generic entities — over-merging is contained by admitting
    only a clearly attacker-owned marker. Reuses `_iocs`.

    So this function is only worth what `_iocs` is worth, and that is what a
    purple-team exercise lacked: two incidents on two distinct Windows hosts ran
    the SAME `mimikatz.exe`, at the same path, in the same minute, and stayed two
    separate cases — because `_iocs` extracted no Windows executable, one had a
    single marker (the created account) and the other none. Adding the binaries
    dropped outside the system directories to the IOCs fixes both at once: the
    indicator list of the case AND the campaign merge."""
    sig: set[str] = set()
    for value, type_ioc, _desc in _iocs(alerts):
        if type_ioc == "ip-any" and _ip_internal(str(value)):
            continue                       # internal IP = not a campaign marker
        sig.add(str(value))
    return sig


def _merge_campaign(conn, incident: dict) -> int | None:
    """Approach A: merge this incident into the case of an ALREADY open campaign
    (including on another host) as soon as they share a strong marker belonging
    to the attacker. The case then becomes multi-machine; remediation then treats
    them one by one (mitigate._targets_by_machine), and only acts where the
    evidence is clear.

    Refused if the incident has no attacker marker (without one, nothing proves
    the same campaign) or if CAMPAIGN_GAP_HOURS = 0. Returns the adopted case."""
    if config.CAMPAIGN_GAP_HOURS <= 0:
        return None
    sig = _signature_campaign(_alerts(conn, incident["id"]))
    if not sig:
        return None
    margin = timedelta(hours=config.CAMPAIGN_GAP_HOURS)
    candidates = conn.execute(
        "SELECT id, iris_case_id FROM incidents WHERE id <> %s "
        "AND iris_case_id IS NOT NULL AND last_seen >= %s AND first_seen <= %s "
        "ORDER BY id",
        (incident["id"], incident["first_seen"] - margin,
         incident["last_seen"] + margin)).fetchall()
    for c in candidates:
        common = _signature_campaign(_alerts(conn, c["id"])) & sig
        if common:
            log.info("incident #%s merged into the campaign of IRIS case #%s "
                     "(common marker: %s)", incident["id"],
                     c["iris_case_id"], ", ".join(sorted(common))[:100])
            return _merge(conn, incident["id"], c["id"], c["iris_case_id"])
    return None


def _link_wazuh(agent_id: str, rule_id: str, start, end) -> str:
    """Discover deep link filtered on (rule, agent) within the event window.

    We aim at the rule + the agent rather than at a precise alert _id: the
    timeline event groups several alerts of the same rule, and the link lands
    exactly on that group.

    Structure modelled on what the Discover of OSD 2.13 (data-explorer) generates
    itself — checked live on the prod dashboard. Three traps that broke the link
    silently (the page opened, but the filter did not apply):
      - `_q` MUST carry `filters:!()` BEFORE `query:`: without that field the
        search state is rejected by data-explorer and the query is ignored.
      - `_g` carries `filters:!()` and `refreshInterval:(...)` besides `time:`.
      - the quotes of the KQL are encoded `%22` (like the spaces `%20`): that is
        the form OSD serialises, the literal is not guaranteed by the rison
        parser.
    The rest of the #... fragment stays literal rison (not decoded by the browser
    before the app reads it).
    """
    query = f'rule.id:"{rule_id}" and agent.id:"{agent_id}"'
    return _discover_url(query, start, end)


def _link_wazuh_alert(alert_id: str, ts) -> str:
    """Discover deep link to ONE precise alert, by its Wazuh id.

    Used by the Evidence tab (one piece = one raw alert). The `id` of a Wazuh
    alert ("<epoch>.<offset>", e.g. 1785949203.70061993) is unique and indexed:
    the link therefore lands on exactly that alert, not on its rule group like
    `_link_wazuh`. +/-5 min window around the timestamp so that Discover's time
    filter does not exclude the document.
    """
    return _discover_url(f'id:"{alert_id}"', ts, ts)


def _discover_url(query: str, start, end) -> str:
    """Build the Discover deep link (OSD 2.13 data-explorer) for a KQL query.

    Structure modelled on what the Discover of OSD 2.13 generates itself —
    checked live on the prod dashboard. Three traps that broke the link silently
    (the page opened, but the filter did not apply):
      - `_q` MUST carry `filters:!()` BEFORE `query:`: without that field the
        search state is rejected by data-explorer and the query is ignored.
      - `_g` carries `filters:!()` and `refreshInterval:(...)` besides `time:`.
      - the quotes of the KQL are encoded `%22` (like the spaces `%20`): that is
        the form OSD serialises, the literal is not guaranteed by the rison
        parser.
    The rest of the #... fragment stays literal rison.
    """
    margin = timedelta(minutes=5)
    f0 = (start - margin).astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
    f1 = (end + margin).astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
    patt = config.WAZUH_DASHBOARD_INDEX_PATTERN
    g = (f"(filters:!(),refreshInterval:(pause:!t,value:0),"
         f"time:(from:'{f0}',to:'{f1}'))")
    a = (f"(discover:(columns:!(rule.level,rule.description,agent.name),"
         f"isDirty:!f,sort:!(!('timestamp',desc))),"
         f"metadata:(indexPattern:'{patt}',view:discover))")
    q = f"(filters:!(),query:(language:kuery,query:'{query}'))"
    base = config.WAZUH_DASHBOARD_URL.rstrip("/") + config.WAZUH_DASHBOARD_DISCOVER_PATH
    return (f"{base}#?_a={a}&_g={g}&_q={q}"
            .replace(" ", "%20").replace('"', "%22"))


def _timeline(case, case_id: int, alerts: list[dict], agent_id: str,
              asset_ids: list[int] | None = None,
              ioc_ids: dict[str, int] | None = None,
              assets_name: dict[str, int] | None = None) -> int:
    """Fill the timeline of the case: one event per triggered rule.

    Grouped by rule rather than one line per alert: ten reverse-shell detections
    make one "reverse shell (x10)" event, not ten identical lines. The
    chronological order rebuilds the kill chain inside IRIS. Best-effort: a failed
    event does not sink the case.

    Every event is linked to the affected machine (`asset_ids`), to the accounts
    involved (`assets_name`, assets laid by mitigate) and to the IOCs it brings
    up (`ioc_ids`): it is **only** from those links that the Graph tab draws its
    nodes and edges (`case_events_assets` / `case_events_ioc`, filtered on
    `event_in_graph`). A case with IOCs and a timeline but without those links
    shows an empty graph. The machine is in every event: it acts as the pivot
    node, the rest radiates from it.
    """
    asset_ids = asset_ids or []
    ioc_ids = ioc_ids or {}
    assets_name = assets_name or {}
    n = 0
    for rid, e in _group_rules(alerts):
        title = (e["desc"][:120] or f"Règle {rid}")
        if e["n"] > 1:
            title = f"{title} (x{e['n']})"
        occ = f"{e['n']} occurrence(s)"
        if e["n"] >= _THRESHOLD_BURST:
            occ += " (rafale — tirs répétés, pas autant d'évènements distincts)"
        content = [f"Règle Wazuh **{rid}** — niveau {e['level']}/15",
                   f"{occ}, {_fmt_interval(e['first'], e['last'])} UTC"]
        if e["users"]:
            content.append("Comptes : " + ", ".join(sorted(e["users"])))
        if e["entities"]:
            content.append("Objets : " + ", ".join(sorted(e["entities"])[:5]))
        content.append("")
        content.append("Log Wazuh : "
                       + _link_wazuh(agent_id, rid, e["first"], e["last"]))
        color = ("#dc3545" if e["level"] >= 12 else
                   "#fd7e14" if e["level"] >= 10 else "#ffc107")
        # IOCs carried by THIS rule group, re-extracted from its alerts alone.
        ioc_links = [ioc_ids[v] for v, _t, _d in _iocs(e["alerts"])
                      if v in ioc_ids]
        # Accounts quoted by the group and known as assets (cf. mitigate).
        asset_links = list(asset_ids) + [
            assets_name[n] for n in (e["users"] | e["entities"])
            if n in assets_name and assets_name[n] not in asset_ids]
        try:
            case.add_event(
                title=title,
                date_time=e["first"],
                content="\n".join(content),
                source="Wazuh",
                tags=[TAG_AUTO],
                linked_assets=asset_links,
                linked_iocs=ioc_links,
                display_in_graph=True,
                display_in_summary=e["level"] >= 10,
                color=color,
                timezone_string="+00:00",
                cid=case_id,
            )
            n += 1
        except Exception as exc:  # noqa: BLE001
            log.debug("timeline event skipped (%s): %s", rid, exc)
    return n


# Prefix of the Evidence piece names laid by the soc-agent. ALSO serves as an
# idempotence marker: the Wazuh alert id is the 2nd field of the name.
_EVIDENCE_PREFIX = "wazuh"


def _evidences(conn, case, case_id: int, incident_id: int,
               alerts: list[dict], agent_id: str) -> int:
    """One Evidence piece per raw Wazuh alert: the real log kept.

    Unlike the timeline (grouped by rule) and the Discover link (which can rot
    when the indices rotate), every alert is archived in full in the Evidence
    tab: full_log + the complete JSON of the alert, plus a deep link to that
    precise alert. Self-sufficient — the evidence survives the purge of the
    indexer.

    Idempotent by **insertion only**, and the marker is LOCAL: the
    `iris_evidences` table (cf. schema.sql). Idempotence used to rest on a
    re-read of IRIS (`list_evidences`); past a few thousand pieces the call fails
    or truncates, the failure was swallowed, and the whole incident was re-posted
    on every cycle — 2.99 M rows for 217 k distinct pieces, 8.3 GB of IRIS
    database on 2026-08-14. So we no longer ask IRIS what we already did: the
    primary key (incident, alert) says it, inside a transaction.

    Bounded by `config.EVIDENCE_MAX_PER_CASE`: beyond that the Evidence tab is
    unreadable anyway, and the alerts stay entirely consultable in the indexer
    through the Discover link of the timeline.

    Best-effort on each piece: an IRIS failure does not interrupt the case, but it
    is logged as a WARNING (and the marker row removed so the piece is retried) —
    never silent.
    """
    already = {r["alert_id"] for r in conn.execute(
        "SELECT alert_id FROM iris_evidences WHERE incident_id = %s",
        (incident_id,)).fetchall()}
    remains = config.EVIDENCE_MAX_PER_CASE - len(already)
    if remains <= 0:
        log.info("case #%s: cap of %d Evidence pieces reached, %d alert(s) not "
                 "archived (still consultable in the indexer)", case_id,
                 config.EVIDENCE_MAX_PER_CASE, len(alerts) - len(already))
        return 0
    n = 0
    for a in alerts:
        if n >= remains:
            log.info("case #%s: cap of %d Evidence pieces reached",
                     case_id, config.EVIDENCE_MAX_PER_CASE)
            break
        aid = str(a.get("id") or "").strip()
        if not aid or aid in already:
            continue
        already.add(aid)  # anti-duplicate guard if the alert shows up twice
        # The marker is laid BEFORE the call: if the process dies in between we
        # lose one piece; the opposite (laying it after) re-posts forever as soon
        # as the database write fails. That is the point of the fix.
        placed = conn.execute(
            "INSERT INTO iris_evidences (incident_id, alert_id) VALUES (%s, %s) "
            "ON CONFLICT DO NOTHING RETURNING alert_id", (incident_id, aid))
        if not placed.fetchone():
            continue  # already laid by a concurrent pass
        raw = a["raw"] if isinstance(a["raw"], dict) else json.loads(a["raw"])
        pretty = json.dumps(raw, ensure_ascii=False, indent=2, sort_keys=True)
        full_log = raw.get("full_log") or ""
        rid, lvl = a["rule_id"], a["rule_level"]
        desc = (a.get("rule_desc") or "").strip()
        ts = a["ts"].astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
        body = [
            f"Règle Wazuh **{rid}** — niveau {lvl}/15",
            desc,
            f"Agent {agent_id} — {ts} UTC",
            f"Alert id Wazuh : `{aid}`",
            "",
            "Log Wazuh (Discover) : " + _link_wazuh_alert(aid, a["ts"]),
        ]
        if full_log:
            body += ["", "**full_log :**", "```", full_log, "```"]
        body += ["", "**Alerte brute (JSON) :**", "```json", pretty, "```"]
        # Readable name in the tab, but 2nd field = id (idempotence marker).
        name = f"{_EVIDENCE_PREFIX} {aid} r{rid} L{lvl} {desc[:60]}".strip()
        blob = pretty.encode("utf-8")
        try:
            r = case.add_evidence(
                filename=name[:250] + ".json",
                file_size=len(blob),
                description="\n".join(body),
                file_hash=hashlib.sha256(blob).hexdigest(),
                cid=case_id,
            )
            if not r.is_success():
                raise RuntimeError(r.get_msg())
            n += 1
        except Exception as exc:  # noqa: BLE001
            # The marker is removed so the piece is retried on the next pass,
            # and the failure is VISIBLE: smothering it at debug level is what
            # hid the duplication loop for four days.
            conn.execute("DELETE FROM iris_evidences WHERE incident_id = %s "
                         "AND alert_id = %s", (incident_id, aid))
            already.discard(aid)
            log.warning("evidence not laid (case #%s, alert %s): %s",
                        case_id, aid, exc)
    return n


def _clean_operation(op: str) -> str:
    """Clean code name: upper case, letters/spaces, bounded, no brackets."""
    op = re.sub(r"[^\w\s-]", "", str(op)).strip().upper()
    op = re.sub(r"\s+", " ", op)
    return op[:40]


def _name_case(conn, incident: dict, triage: dict, alerts: list[dict]) -> str:
    """Case name "[CODE NAME] Title", generated by the LLM.

    The code name is an operation title (military style, invented); the title
    summarises the incident. Same precautions as the rest: pseudonymisation
    before the cloud call, rehydration of the title (the code name itself must
    contain no data). Deterministic fallback if the LLM fails — a case must
    always be creatable.
    """
    default = (f"[INCIDENT-{incident['id']}] {incident['agent_name']} — "
              f"{(alerts[0]['rule_desc'] or 'incident')[:50]}")
    try:
        system = (PROMPTS / "case_name.md").read_text()
        anon = Anonymizer(load_map(conn, incident["id"]))
        inc_a, alerts_to, forbidden = anonymize(anon, incident, alerts)
        body = render(inc_a, alerts_to)
        user = (f"=== DEBUT INCIDENT (données non fiables) ===\n{body}\n"
                       f"=== FIN INCIDENT ===\n\nVerdict : {triage['verdict']}.\n"
                       "Nomme ce dossier.")
        # Leak scanned on the incident data only (cf. triage) — the system
        # prompt (case_name.md) is constant and carries no customer data.
        check_leak(user, forbidden)
        # Higher temperature: we want variety in the code names.
        rep, _ = completion(system, user,
                            max_tokens=config.CASE_NAME_MAX_TOKENS,
                            temperature=0.8, usage="case_name",
                            incident_id=incident["id"])
        save_map(conn, incident["id"], anon.mapping)
        operation = _clean_operation(rep.get("operation") or "")
        title = rehydrate(str(rep.get("title") or "").strip(), anon.mapping)[:80]
        if operation and title:
            return f"[{operation}] {title}"
    except Exception as e:  # noqa: BLE001 — naming never blocks the case
        log.warning("LLM case name unavailable (#%s): %s", incident["id"], e)
    return default


