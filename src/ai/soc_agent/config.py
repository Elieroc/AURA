# What actually bounds it is the shape of the name: only DAY-DATED indices
# (`-YYYY.MM.DD`) are archived. Excluded by construction, with no list:
# `wazuh-voc-vulns` (an undated state index, it carries the MTTR),
# `wazuh-monitoring-*` and `wazuh-statistics-*` (dated to the week, Wazuh's
# internal telemetry). The month is read from the index NAME, never from an
# `@timestamp`: no time zone in the equation.
ARCHIVE_INDEX_PATTERNS = os.environ.get("ARCHIVE_INDEX_PATTERNS", "wazuh-*")

# Additional exclusions, as glob patterns on the full index name.
#
# The threat hunting space is ALWAYS in there, whatever is put in the variable:
# it holds copies restored from the archives, re-archiving them would mean
# archiving an archive — and under Object Lock, paying twice for the same data
# for twelve months. The hunting index names are already not day-dated, so they
# are excluded by shape; this line is the second barrier, the one that holds even
# if the naming changes.
ARCHIVE_INDEX_EXCLUDED = [
    m.strip() for m in os.environ.get("ARCHIVE_INDEX_EXCLUDED", "").split(",")
    if m.strip()] + [f"{HUNTING_INDEX_BASE}-*"]

# Fields removed from `_source` before writing (OpenSearch patterns, `a.b.*`
# accepted). EMPTY by default, and that is a choice: a truncated archive does not
# repair itself, and the saving would be a few gigabytes a year — the order of
# magnitude of the price of a coffee. Only to be filled in if volume becomes a
# real problem, and to be documented in the manifest (which `excluded_fields`
# does).
ARCHIVE_EXCLUDED_FIELDS = [
    c.strip() for c in os.environ.get("ARCHIVE_EXCLUDED_FIELDS", "").split(",")
    if c.strip()]

# zstd level. 19 is the best trade-off on alert JSON (~20-30x); beyond it
# (`--ultra`) the gain is marginal and the memory blows up.
ARCHIVE_ZSTD_LEVEL = int(os.environ.get("ARCHIVE_ZSTD_LEVEL", "19"))

# Grace delay after the end of the month before archiving it. This is not
# decorative caution: the catch-up of late-indexed alerts (see INGEST_SWEEP_*)
# and an index created across midnight can still write into the elapsed month.
# Archiving too early freezes an incomplete copy.
ARCHIVE_DELAY_DAYS = int(os.environ.get("ARCHIVE_DELAY_DAYS", "2"))

# Archive retention, in months. Serves as a reference for the manifest and the
# gap check: the deletion itself belongs to the bucket's LIFECYCLE RULE, not to
# this code. A cron that dies must not grow the bill forever, and the code is not
# allowed to delete (the production application key does not carry
# `deleteFiles`).
ARCHIVE_RETENTION_MONTHS = int(os.environ.get("ARCHIVE_RETENTION_MONTHS", "12"))

# Safety margin between archiving and the ISM purge, in days. An index entering
# this margin without a confirmed archive is REMOVED from the ISM policy by
# `retention.py`: it stops being a candidate for deletion until its copy exists.
# That is the only mechanism actually preventing the loss — suspending the
# setting of the policy would not be enough, it is already attached to the
# indices and would keep deleting them.
ARCHIVE_MARGIN_DAYS = int(os.environ.get("ARCHIVE_MARGIN_DAYS", "7"))

# Page size of the export (scroll). 5,000 Wazuh alert documents weigh ~15 MB in
# JSON: going much higher grows the indexer's response without speeding the
# export up.
ARCHIVE_BATCH_SIZE = int(os.environ.get("ARCHIVE_BATCH_SIZE", "5000"))

# Restore drill. On every pass, the N archives verified least recently are
# downloaded again, their SHA-256 recomputed, then DECRYPTED and recounted
# against their manifest. An untested archive is a belief, not a copy.
#
# The drill goes as far as decryption because the SOC holds its key: it therefore
# proves READABILITY, not only the integrity of the storage. That is the main
# operational benefit of the symmetric key choice.
#
# FULL=false stops at the SHA-256 of the object. Useful transiently (key
# momentarily absent) so as not to declare failed what we simply could not
# read.
ARCHIVE_DRILL_BATCH = int(os.environ.get("ARCHIVE_DRILL_BATCH", "3"))
ARCHIVE_DRILL_DAYS = int(os.environ.get("ARCHIVE_DRILL_DAYS", "90"))
ARCHIVE_DRILL_FULL = os.environ.get(
    "ARCHIVE_DRILL_FULL", "true").lower() == "true"

# Working directory. The archive is written there ALREADY ENCRYPTED — the
# plaintext never touches the disk, it only crosses pipes. Plan for room: the
# module refuses to start an export if it has nothing to write it with, because a
# full disk stops the whole SOC (see docs/RETENTION.md).
ARCHIVE_TMP_DIR = os.environ.get("ARCHIVE_TMP_DIR", "/tmp")

# --- Archive dashboard (see archive_metrics.py, docs/ARCHIVAGE.md) ---------
#
# The catalog (`archives_s3`) is exported to this fixed-name index (no date
# suffix, one document per (index set, month)) so it can be read in a Wazuh
# dashboard next to the alerts. No `-*` date rotation: unlike alerts, an
# archive doesn't happen every day, and there is nothing to purge — a state
# index, same convention as `wazuh-voc-vulns`. Its very name keeps it out of
# `archive.py`'s own scan (`_DATE_INDEX` requires a `-YYYY.MM.DD` suffix).
ARCHIVE_METRICS_INDEX = os.environ.get(
    "ARCHIVE_METRICS_INDEX", "wazuh-archive-catalog")

# Backblaze B2's published rate (see docs/ARCHIVAGE.md), USD per GB per month.
# An estimate, like `LLM_COST_USD_PER_MTOKEN_*`: it prices the ENCRYPTED
# object actually stored, not the plaintext, and says nothing about egress
# (free up to 3x the stored volume, so irrelevant to a monthly figure).
ARCHIVE_S3_COST_USD_PER_GB_MONTH = float(
    os.environ.get("ARCHIVE_S3_COST_USD_PER_GB_MONTH", "0.00695"))

# --- Disk guardrail (see watchdog.py) ---------------------------------------
#
# Six gigabytes a day were going without anything saying so. A SOC that does not
# watch its own disk stops silently: indexer read-only, Postgres refusing to
# write, no alert entering any more.
DISK_MONITORED = os.environ.get("DISK_MONITORED", "/")
# Occupancy thresholds, as percentages. `alert` opens a Medium IRIS alert,
# `critical` raises it to High — same channel, same life cycle.
DISK_THRESHOLD_ALERT = int(os.environ.get("DISK_THRESHOLD_ALERT", "80"))
DISK_THRESHOLD_CRITICAL = int(os.environ.get("DISK_THRESHOLD_CRITICAL", "90"))
