# --- Threat hunting: restore index set (see hunting.py) ----------------------
#
# `wazuh-hunting-*` is NOT a routing index set. No log source writes to it, no
# branch of the ingest pipeline points at it: it is the workspace where archived
# data is PUT BACK to hunt in.
#
# It therefore deliberately lacks two of the five pieces of an index set (see
# docs/ROUTAGE.md), and that absence is the feature:
#
#  - **not read by ingestion.** Re-ingesting ten-month-old alerts would bring
