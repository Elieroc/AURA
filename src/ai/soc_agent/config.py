# Cap on the duration of ONE query, applied to every soc-agent connection.
#
# Without it, a query gone wrong ties up its session forever, and everything
# needing a lock on the same tables waits behind — observed on 2026-08-11, a
# migration `ALTER TABLE` stuck behind cycle sessions. A query of this pipeline
# lasting more than five minutes is abnormal anyway: the big batches are split
# (INGEST batch size, UEBA_BATCH).
#
# Deliberately NO idle_in_transaction_session_timeout: the cycle holds its
# advisory lock inside a transaction open for its whole run (see cycle.LOCK).
# Killing it on inactivity would release the lock and allow two concurrent
# cycles — the cure would be worse than the disease.
PG_STATEMENT_TIMEOUT_MS = int(
    os.environ.get("PG_STATEMENT_TIMEOUT_MS", "300000"))


def _with_statement_timeout(dsn: str, ms: int) -> str:
    """Adds `options=-c statement_timeout=<ms>` to the DSN, overwriting nothing.

    Going through the DSN rather than a `SET` after connecting: there is no
    single choke point where every connection is opened (each module does its own
    `psycopg.connect`), so the only place covering them all is the connection
    string itself.
    """
    if ms <= 0 or "options=" in dsn:
        return dsn
    opt = f"-c statement_timeout={ms}"
    if dsn.startswith(("postgresql://", "postgres://")):
        from urllib.parse import quote
        return f"{dsn}{'&' if '?' in dsn else '?'}options={quote(opt)}"
    return f"{dsn} options='{opt}'"


PG_DSN = _with_statement_timeout(PG_DSN, PG_STATEMENT_TIMEOUT_MS)

