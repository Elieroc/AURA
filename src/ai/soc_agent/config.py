CLOSURE_FORBIDDEN_BY_PRIORITY = {
    p + 1: int(v) for p, v in enumerate(
        os.environ.get("CLOSURE_FORBIDDEN_BY_PRIORITY", "12,13,14,14").split(","))}

# Priority forced for a SENSOR agent (AGENTS_SENSORS). Its telemetry describes
# the activity of OTHER machines: the firewall carrying Suricata is indeed a P1
# asset, but the alerts it REPORTS are about LAN workstations. Without this
