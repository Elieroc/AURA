# --- Catching up with late-indexed alerts -----------------------------------
#
# The ingestion cursor advances on `@timestamp`, the date of the EVENT, not of
# its indexing. Any alert becoming visible to search AFTER the cursor has passed
# its timestamp is skipped for good. Two scales of lateness, two answers.
#
# 1. Indexing skew (seconds to minutes): agent -> manager -> indexer transit plus
#    the index refresh. We resume ingestion slightly before the recorded
#    position. The overlap is free, the insert being idempotent (ON CONFLICT DO
#    NOTHING on the native Wazuh id).
INGEST_LOOKBACK_MINUTES = int(os.environ.get("INGEST_LOOKBACK_MINUTES", "15"))

