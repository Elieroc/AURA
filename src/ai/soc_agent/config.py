TRAINING_MAX_LEVEL = int(os.environ.get("TRAINING_MAX_LEVEL", "15"))

# --- UEBA (behavioural analysis of the LOW/MEDIUM alerts) -------------------
#
# The third reduction stage, between the VT filter and the LLM (see ueba.py). It
# builds a baseline of normal behaviour per machine and per account, scores the
# RARITY of what happens in bits of information, and promotes the best-scoring
# concentrations to incident seeds. Goal: see the quiet intrusion that only emits
# level 3-11, without sending the noise to the LLM.
UEBA_ENABLED = os.environ.get("UEBA_ENABLED", "true").lower() == "true"

# Maturity of a profile. A scope that is too young is NOT scored: on day one
# everything in it is unseen — scoring would send the whole estate to the LLM. We
# observe first, we judge afterwards. Same philosophy as training mode, and the
# two combine well: the training window seeds the baseline for free.
UEBA_MATURITY_DAYS = int(os.environ.get("UEBA_MATURITY_DAYS", "7"))
UEBA_MATURITY_MIN_OBS = int(os.environ.get("UEBA_MATURITY_MIN_OBS", "200"))

# Bits given to a value NEVER seen in a mature profile. 12 bits = "one chance in
# 4096", the order of magnitude of a genuinely novel event.
UEBA_FIRSTSEEN_BITS = float(os.environ.get("UEBA_FIRSTSEEN_BITS", "12"))

# Number of hosts from which a value unseen HERE is judged mundane ELSEWHERE
# (admin rollout, update, business tool): its score is then crushed. The module's
# main anti-false-positive — without it, every new binary pushed onto the estate
# would open one incident per machine.
UEBA_FLEET_COMMON = int(os.environ.get("UEBA_FLEET_COMMON", "3"))

# Number of DISTINCT days beyond which a value is a habit and stops being
# scored. In days and not in occurrences: 500 executions in a single day is an
# incident, 5 executions over 5 days is a routine.
UEBA_DAYS_USUAL = int(os.environ.get("UEBA_DAYS_USUAL", "5"))

# CARDINALITY guardrail. A trait where nearly every observation brings a new
# value (timestamped paths, rotating LVM archives, GUIDs, session identifiers) is
# unseen by construction: "never seen" means nothing there, and it saturates the
# score permanently. Measured at go-live: the LVM archives of the Proxmox host
# alone gave a 1434-point signal, forty times the floor.
#
# We judge on the RATIO of distinct values to observations rather than on a list
# of patterns: no blacklist anticipates what an estate produces, the statistic
# corrects itself. Below MIN_OBS we do not conclude (we do not exclude a trait
# for lack of hindsight).
#
# The 0.25 threshold is not picked by eye: measured on the real estate, the
# pathological trait (LVM archives) is at 0.481 and the next one at 0.056 — an
# order of magnitude apart. 0.25 falls in the middle of the gap, hence far from
# both.
UEBA_CARDINALITY_MAX = float(os.environ.get("UEBA_CARDINALITY_MAX", "0.25"))
UEBA_CARDINALITY_MIN_OBS = int(os.environ.get("UEBA_CARDINALITY_MIN_OBS", "200"))

# Rarity floor: below it the trait is not kept as a pattern. Avoids stacking
# tenths of a bit that would end up crossing the threshold without a single
# element being abnormal.
UEBA_BITS_MIN_RARITY = float(os.environ.get("UEBA_BITS_MIN_RARITY", "4"))

# Saturation caps. Without them, a single value repeated a thousand times
# crushes everything else and the score stops describing the incident.
UEBA_CAP_TRAIT = float(os.environ.get("UEBA_CAP_TRAIT", "14"))
UEBA_CAP_ALERT = float(os.environ.get("UEBA_CAP_ALERT", "20"))

# Window grouping the low alerts of one agent into a "signal". Wider than
# CORRELATION_GAP_MINUTES: a quiet intrusion is slow, and here we are not looking
# for nameable common ground but for a CONCENTRATION.
UEBA_WINDOW_MINUTES = int(os.environ.get("UEBA_WINDOW_MINUTES", "60"))

# Maximum total duration of a signal. The chaining is step by step: without this
# cap, a host emitting one alert every 50 minutes glues its whole day into a
# single signal — the score swells by accumulation rather than by anomaly. The
# equivalent of MAX_INCIDENT_HOURS for correlation.
UEBA_SIGNAL_MAX_HOURS = int(os.environ.get("UEBA_SIGNAL_MAX_HOURS", "6"))

# MITRE chain. A plain "3 distinct tactics" mostly surfaces Discovery x3 (an
# admin inventorying their machine): the tactics are therefore WEIGHTED
# (credential-access = 5, discovery = 1) and a bonus is added when they PROGRESS
# along the kill chain order.
UEBA_MIN_TACTICS = int(os.environ.get("UEBA_MIN_TACTICS", "3"))
UEBA_BONUS_ORDER = float(os.environ.get("UEBA_BONUS_ORDER", "3"))

# Minimum score for a signal to be promotable. Calibrated on real data WITHOUT
# spending a token: `python -m soc_agent.ueba --simulation` records the signals
# and their scores without promoting anything.
UEBA_SCORE_FLOOR = float(os.environ.get("UEBA_SCORE_FLOOR", "35"))

# THE cost guardrail. A score threshold alone bounds nothing: the volume varies
# by a factor of ten between a quiet day and a campaign. The budget, in contrast,
# is a number we decide. A signal not promoted is not lost — it is re-evaluated
# on the next cycle, and its score will have grown if it continues.
# 20 promotions/day ~ 20 LLM triages/day added to the existing cost.
UEBA_BUDGET_PER_DAY = int(os.environ.get("UEBA_BUDGET_PER_DAY", "20"))
UEBA_BUDGET_PER_CYCLE = int(os.environ.get("UEBA_BUDGET_PER_CYCLE", "2"))

# Age beyond which a low alert is no longer a candidate for a signal: it had its
# chances, taking it back forever would grow the batch without end.
UEBA_RETENTION_HOURS = int(os.environ.get("UEBA_RETENTION_HOURS", "24"))

# Size of the observation batch per pass. The very first pass has to swallow the
# history already in database; the following ones only see the cycle's delta.
UEBA_BATCH = int(os.environ.get("UEBA_BATCH", "20000"))

# Memory of the baseline. A profile that never ages freezes the behaviour of six
# months ago: a reinstalled server would stay "normal" on its old binaries. Older
# observations are deleted and the profiles recomputed on what is left.
UEBA_MEMORY_DAYS = int(os.environ.get("UEBA_MEMORY_DAYS", "90"))

# Autonomous remediation on an incident coming from a UEBA signal.
#
# FALSE by default, deliberately. The rest of the pipeline acts without human
