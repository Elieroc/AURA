# queue — prioritisation would degrade the ordering instead of improving it.
PRIORITY_SENSOR = int(os.environ.get("PRIORITY_SENSOR", "3"))


# --- Correlation ------------------------------------------------------------
#
# Two alerts of the same agent less than CORRELATION_GAP_MINUTES apart and
# sharing common ground (MITRE tactic, rule group or entity) are attached to the
# same incident. Proximity chaining: A-B and B-C also attach A-C, even when A and
# C are far apart.
CORRELATION_GAP_MINUTES = int(os.environ.get("CORRELATION_GAP_MINUTES", "30"))

# Widened window for STRONG links — same source IP, same file, same account. A
# hostile IP coming back three times in a day is one campaign; with the 30-minute
# window alone it produced three distinct incidents, hence three LLM triages for
# the same subject.
ENTITY_GAP_MINUTES = int(os.environ.get("ENTITY_GAP_MINUTES", "360"))

# Guardrail against endless chaining: on a noisy host, one alert every 25
# minutes would merge a whole week into a single unreadable incident.
MAX_INCIDENT_HOURS = int(os.environ.get("MAX_INCIDENT_HOURS", "6"))

# CAMPAIGN merge window: incidents from several hosts gathered into a single
# case when they share a STRONG marker belonging to the attacker (created
# account, external C2 IP, malicious file). Wider than MAX_INCIDENT_HOURS because
# a campaign spreads over days; the risk of over-merging is bounded by the
# requirement of a shared attacker marker (never an internal IP nor a generic
# entity). 0 disables the campaign merge.
CAMPAIGN_GAP_HOURS = int(os.environ.get("CAMPAIGN_GAP_HOURS", "48"))

# Lifetime of the automatic RE-TRIAGE of an incident (fix #4, the token
# explosion of 2026-07-30). Past this delay from `first_seen`, an
# already-triaged incident is no longer re-triaged even when it gains alerts
# (`needs_refresh`): otherwise an incident from the noisy estate gets
# re-analysed by the LLM every 5 min for life (observed: incidents several days
# old still burning 18-25 LLM calls a day). A new intrusion reopens a fresh
# incident through the correlation windows anyway. 0 disables the cap (re-triage
# with no age limit). Does NOT affect creation (an incident never triaged is
# always triaged, whatever its age).
INCIDENT_REFRESH_TTL_HOURS = int(
    os.environ.get("INCIDENT_REFRESH_TTL_HOURS", "48"))

# --- "Silent sensor" watchdog (watchdog.py) ---------------------------------
# A sensor that was talking and goes quiet is a blind spot no rule sees. The rule
# groups watched: their silence makes whole swathes of the ruleset inert (audit
# -> 1006xx/1007xx; suricata -> network detection; sshd/pam -> brute-force).
# Adding an application group is easy if needed.
WATCHDOG_SENSORS = tuple(os.environ.get(
    "WATCHDOG_SENSORS", "audit,suricata,sshd,syscheck").split(","))
# Reference window: over how many hours a sensor is judged "established".
WATCHDOG_REF_HOURS = int(os.environ.get("WATCHDOG_REF_HOURS", "168"))  # 7 j
# Minimum volume over the reference window so as not to alert on an anecdotal
# sensor (a single isolated event is not a baseline).
WATCHDOG_BASELINE_MIN = int(os.environ.get("WATCHDOG_BASELINE_MIN", "20"))
# Silence tolerated before declaring the OUTAGE. 10 min, an operator setting of
# 2026-08-11, consistent with the real cadence of the continuous sensors measured
# over 7 days of data: gap between two events, p95 / max
#
#     audit      5.4 min / 8.3 min
#     suricata   0.0 min / 3.7 min
#
# A 10-minute silence on those two is therefore no longer explained by a lull in
# traffic. The EVENT-DRIVEN sensors (sshd, syscheck) have their own threshold
# below: for them silence is the normal state.
WATCHDOG_SILENCE_MINUTES = int(os.environ.get("WATCHDOG_SILENCE_MINUTES", "10"))

# PER-SENSOR threshold, for those that do not emit continuously.
#
# syscheck is not a stream: FIM only alerts on a CHANGE (rules
# 550/553/554/594/750 — there is no end-of-scan event to hook onto), and the
# scheduled scan runs every 12 h (Wazuh default, no <frequency> in the shared
# agent.conf). A quiet estate therefore produces nothing for hours, which is the
# intended behaviour. With the 90-minute default, the watchdog cried "silent
# sensor" on every agent every day between noon and 11 p.m.: a permanent alarm
# that teaches people to ignore the watchdog, which costs more than the gap it
# claims to cover.
#
# 840 min (a 12 h cycle plus 2 h) was still too short, and 2026-08-12 showed it:
# case #212 opened on `admin` for a perfectly healthy sensor. The scan ran on
# schedule (last on 2026-08-11 23:12, 2004 files tracked), and the last CHANGE
# dated from 2026-08-10 — an `update-ca-certificates`. Nothing had simply
# happened on that machine since.
#
# Maximum gap actually observed between two syscheck events, over 30 days:
#
#     wazuh.manager  52 h        debian2  19 h
#     admin          29 h        debian3  17 h
#
# 4320 min (3 d) sits above the measured maximum with margin. It is an
# acknowledged patch: the right signal for this sensor is not the alert (which
# depends on a change) but the SCAN itself, which the Wazuh API exposes
# (`/syscheck/<agent>/last_scan`). Until we read it, a genuinely stuck syscheckd
# stays invisible for up to three days.
#
# sshd follows the same reasoning, measured on 2026-08-11 over 7 days: median gap
# between two events 0.2 min, but p95 at 254 min and maximum at 63 h. A host
# nobody logs into emits NOTHING, and that is normal — at a 10-minute threshold,
# every idle machine would be declared down. Worse, a host isolated by
# remediation only accepts SSH from the manager: its sshd sensor goes quiet by
# construction (observed on debian2/3/4, silent since 2026-08-09 because
# isolated, not because broken).
#
# 1440 min (24 h): beyond that, even a forgotten machine should have seen a
# session or a scan. A genuinely stuck journald reader therefore does come out
# eventually, without drowning the analyst in the meantime.
WATCHDOG_SILENCE_PER_SENSOR = {
    "syscheck": int(os.environ.get("WATCHDOG_SILENCE_SYSCHECK", "4320")),
    "sshd": int(os.environ.get("WATCHDOG_SILENCE_SSHD", "1440")),
}

# Where an outage lands in IRIS: `alert` | `case` | `off`.
#
# A silent sensor is a blind spot of the SOC itself: it deserves a record someone
# must acknowledge, not only a log line nobody reads. The question is WHERE.
#
# `case` was the first choice, and it was the wrong one: a case is an
# investigation file, with its notes, its timeline, its IOCs. A sensor outage has
# nothing to investigate — it has a state (silent / recovered) and a gesture
# (acknowledge, or go and repair). The outage cases mixed with the incident cases
# in the same queue, where they diluted what matters.
#
# `alert` (the default since 2026-08-13) files them in the Alerts tab, which
# carries exactly that life cycle (New / Assigned / Closed) and leaves the
# "Escalate to case" button to the analyst: THEY decide an outage deserves a
# file, which the `case` channel decided in their place.
#
# `case` stays available, and outages opened BEFORE a switch are closed in their
# original channel (see watchdog.monitor).
WATCHDOG_IRIS_CHANNEL = os.environ.get("WATCHDOG_IRIS_CHANNEL", "alert").lower()
# Backwards compatibility: `WATCHDOG_CASE_IRIS=false` used to cut every IRIS record.
if os.environ.get("WATCHDOG_CASE_IRIS", "true").lower() != "true":
    WATCHDOG_IRIS_CHANNEL = "off"
if WATCHDOG_IRIS_CHANNEL not in ("alert", "case", "off"):
    WATCHDOG_IRIS_CHANNEL = "alert"

