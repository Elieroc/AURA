# --- The SOC's own infrastructure -------------------------------------------
#
# Defined at the end of the file: it depends on the URLs declared above.

def _host_url(url: str) -> str | None:
    """Host of a configuration URL, only when it is a literal IP.

    A DNS name is useless here: the comparison will be against the IP as it
    appears in an alert.
    """
    try:
        host = urlparse(url or "").hostname
    except ValueError:
        return None
    if not host:
        return None
    try:
        ipaddress.ip_address(host)
    except ValueError:
        return None
    return host


